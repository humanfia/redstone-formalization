def gen_block_entities(g, out, stub_dir):
    """The `BlockEntity` type, and a stub module for every block entity type that has none."""
    import os
    types = g.dump["blockEntityTypes"]
    for t in types:
        t["short"] = t["id"].split(":", 1)[1]
        t["name"] = camel(t["short"])
        path = f"{stub_dir}/{t['name']}.lean"
        if not os.path.exists(path):
            with open(path, "w") as f:
                f.write(BE_STUB.format(id=t["id"], cls=t.get("class", ""), name=t["name"]))
    o = [g.header("Block entities", [f"Redstone.Block.Entity.{t['name']}" for t in types])]
    o.append("/-- A block entity: the extra data some blocks keep besides their block state. -/")
    o.append("inductive BlockEntity")
    o += [f"  | {ident(lower_first(t['name']))} (d : BlockEntities.{t['name']})" for t in types]
    o.append("  deriving DecidableEq, Repr\n")
    o.append("namespace BlockEntity\n")
    o.append("/-- The registry name of the block entity's type. -/")
    o.append("def typeName : BlockEntity → String")
    o += [f"  | .{ident(lower_first(t['name']))} _ => {lean_str(t['id'])}" for t in types]
    o.append("\n/-- Reads a block entity of the type named `type` from its saved NBT. -/")
    o.append("def ofNbt? (type : String) (nbt : Nbt) : Option BlockEntity :=")
    o.append("  match type with")
    o += [f"  | {lean_str(t['id'])} => .{ident(lower_first(t['name']))} <$> BlockEntities.{t['name']}.ofNbt? nbt"
          for t in types]
    o.append("  | _ => none\n")
    o.append("/-- A new block entity for the block `id`, with default data, if the block has one. -/")
    o.append("def new? : BlockId → Option BlockEntity")
    by_id = {t["id"]: t for t in types}
    for b in g.blocks:
        if b.get("blockEntity"):
            t = by_id[b["blockEntity"]]
            o.append(f"  | .{ident(b['short'])} => some (.{ident(lower_first(t['name']))} default)")
    o.append("  | _ => none\n")
    o.append("end BlockEntity")
    with open(f"{out}/BlockEntity.lean", "w") as f:
        f.write("\n".join(o) + FOOTER)


def gen_shapes(g, grids):
    """`Shapes.lean`: the boxes of every shape of the dump, as the bits of their coordinates, and
    the grids of the collision shapes (`grids`: shapegrids.json, written by ShapeGrids.java)."""
    o = [g.header("Block shapes", ["Mathlib.Tactic"])]
    o.append("namespace Block\n")
    o.append("/-- The shapes that blocks have (`VoxelShape`), numbered as `Attrs.collision`, `Attrs.outline`\n"
             "and `Attrs.supportShape` number them. A shape is given by its boxes, in the order of\n"
             "`VoxelShape.forAllBoxes`; a box is six doubles `minX, minY, minZ, maxX, maxY, maxZ`, given by\n"
             "their IEEE bits, relative to the block. Shape 0 is the empty shape. -/")
    o.append("def shapeBits : Array (Array UInt64) := #[")
    rows = []
    for shape in g.dump["shapes"]:
        rows.append("  #[" + ", ".join("0x" + c for box in shape for c in box) + "]")
    o.append(",\n".join(rows) + "]\n")
    by_boxes = {json.dumps(e["boxes"], separators=(",", ":")): e["coords"] for e in grids["grids"]}
    o.append("/-- The grid of each shape that is the collision shape of some block state: the coordinates\n"
             "of the shape along x, y and z (`VoxelShape.getCoords`), as IEEE bits. The grid cuts the block\n"
             "into cells, and the boxes are unions of cells; it can have more coordinates than the faces of\n"
             "the boxes. The entry of a shape that is no collision shape is empty. -/")
    o.append("def shapeGridBits : Array (Array (Array UInt64)) := #[")
    rows = []
    for shape in g.dump["shapes"]:
        coords = by_boxes.get(json.dumps(shape, separators=(",", ":")))
        if coords is None:
            rows.append("  #[]")
        else:
            rows.append("  #[" + ", ".join("#[" + ", ".join("0x" + c for c in axis) + "]" for axis in coords) + "]")
    o.append(",\n".join(rows) + "]")
    o.append("\nend Block")
    return "\n".join(o) + FOOTER


def item_key(name):
    """`Redstone.itemKey`: the bytes of the name as digits in base 256 below a leading 1."""
    key = 1
    for byte in name.encode("utf-8"):
        key = key * 256 + byte
    return key


def gen_items(g):
    """`Items.lean`: the maximal stack size of every item.

    The table is written twice: as the list of the item names that do not stack to the common
    size, which is what a reader checks against the game, and as a binary search tree on
    `Redstone.itemKey` of those names, which is what the model evaluates (see
    `Redstone/Basic/ItemKey.lean`). `Redstone/Lemmas/ItemStackSize.lean` proves that the tree
    finds exactly what a scan of the list finds, so the two cannot drift apart.
    """
    o = [g.header("Items", ["Redstone.Basic.ItemKey"])]
    sizes = {item["id"]: item["maxStackSize"] for item in g.dump["items"]}
    assert len(sizes) == len(g.dump["items"]), "an item is listed twice"
    counts = defaultdict(int)
    for size in sizes.values():
        counts[size] += 1
    common = max(counts, key=lambda k: counts[k])
    # In ascending order of the key, which is the order of the tree's entries.
    entries = sorted((item_key(i), i, size) for i, size in sizes.items() if size != common)
    assert all(a[0] < b[0] for a, b in zip(entries, entries[1:])), "two items with one key"
    o.append(f"/-- The items that do not stack up to {common}, each with the size of its stacks, in")
    o.append("ascending order of `itemKey`: shorter names first, names of one length in the order of")
    o.append("their bytes. -/")
    o.append("def itemStackSizes : List (String × ℕ) := [")
    o.append(",\n".join(f"  ({lean_str(i)}, {size})" for _, i, size in entries) + "]\n")

    def tree(lo, hi, indent):
        if lo >= hi:
            return [f"{indent}.leaf"]
        mid = (lo + hi) // 2
        key, name, size = entries[mid]
        if hi - lo == 1:
            return [f"{indent}(.node .leaf 0x{key:x} {size} .leaf) -- {name}"]
        return ([f"{indent}(.node"] + tree(lo, mid, indent + " ")
                + [f"{indent} 0x{key:x} {size} -- {name}"] + tree(mid + 1, hi, indent + " ")
                + [f"{indent})"])

    o.append("/-- `itemStackSizes` as a search tree on `itemKey`. -/")
    o.append("def itemStackSizeTable : ItemTable :=")
    o.append("\n".join(tree(0, len(entries), "  ")) + "\n")
    o.append("/-- `Item.getDefaultMaxStackSize`: how many items of the kind named `id` fit in one stack.")
    o.append(f"It is the size `itemStackSizes` lists for the name, and {common} for a name that is not")
    o.append("listed (`itemMaxStackSize_eq_lookup`). -/")
    o.append("def itemMaxStackSize (id : String) : ℕ :=")
    o.append(f"  (itemStackSizeTable.find? (itemKey id)).getD {common}\n")
    return "\n".join(o) + FOOTER


def main():
    dump_path, out = sys.argv[1], sys.argv[2]
    if sys.argv[3:] not in ([], ["--items"]):
        sys.exit(f"unknown arguments: {sys.argv[3:]}")
    g = Gen(json.load(open(dump_path)))
    if sys.argv[3:] == ["--items"]:
        # Only the item table, which needs nothing but the dump.
        with open(f"{out}/Items.lean", "w") as f:
            f.write(gen_items(g))
        return
    gen_block_entities(g, out, f"{out}/../Entity")
    state = g.gen_state()  # also decides which index functions `gen_props` must emit
    attrs = g.gen_attrs()
    grids = json.load(open(os.path.join(os.path.dirname(os.path.abspath(dump_path)), "shapegrids.json")))
    files = {"Props": g.gen_props(), "Id": g.gen_id(), "State": state, "Attrs": attrs,
             "Shapes": gen_shapes(g, grids), "Items": gen_items(g)}
    for name, text in files.items():
        with open(f"{out}/{name}.lean", "w") as f:
            f.write(text)
    with open(f"{out}/families.json", "w") as f:
        json.dump([{"name": fam["name"], "ctor": fam["ctor"], "class": fam["class"],
                    "blocks": [{"id": b["id"], "classes": b["classes"], "blockEntity": b.get("blockEntity")}
                               for b in fam["blocks"]],
                    "props": [p["name"] for p in fam["props"]]} for fam in g.families], f, indent=1)
    print(f"{len(g.blocks)} blocks, {len(g.families)} families, {len(g.enum_defs)} enums, "
          f"{len(g.attr_records)} attribute records, {len(g.tables)} tables")


if __name__ == "__main__":
    main()
