#!/usr/bin/env python3
"""Generates the Lean block inventory from the server's block dump.

    python3 tools/gen/gen_blocks.py $MC_REPORTS/blockdump.json Redstone/Block/Generated

The dump is written by `tools/harness/run.sh dump` (see tests/FORMAT.md). The grids of the
collision shapes are read from `shapegrids.json` next to the dump, which `tools/gen/ShapeGrids.java`
writes. Everything under `Redstone/Block/Generated` is produced by this script and must not be
edited by hand.

With `--items` as a third argument only `Items.lean` is written, the table of the maximal stack
sizes, which needs the dump alone.

Blocks are grouped into *families*: blocks with the same Java class and the same properties.
A family becomes one constructor of `Redstone.Block`, carrying the block id (when the family
has several blocks) and a structure with one field per property. All blocks without properties
form the single family `Plain`.
"""
import json
import os
import re
import sys
from collections import OrderedDict, defaultdict

KEYWORDS = {
    "open", "end", "in", "at", "from", "type", "instance", "structure", "inductive", "class",
    "def", "theorem", "fun", "let", "have", "show", "do", "if", "then", "else", "match", "with",
    "namespace", "section", "import", "private", "protected", "public", "local", "variable",
    "universe", "where", "deriving", "extends", "for", "unless", "return", "try", "catch",
    "finally", "mut", "macro", "syntax", "notation", "infix", "prefix", "postfix", "axiom",
    "example", "abbrev", "opaque", "attribute", "export", "using", "by", "calc", "true", "false",
    "nomatch", "nofun", "meta", "module", "mutual", "partial", "unsafe", "noncomputable", "set_option",
    "initialize", "builtin_initialize", "omit", "include", "elab", "binder_predicate", "this", "all",
}

# Names an enum type must not take, because they mean something else in Lean or in this project.
RESERVED_TYPES = {
    "Type", "Prop", "Sort", "Nat", "Int", "Bool", "String", "Option", "List", "Array", "Fin", "Unit",
    "Block", "BlockId", "Blocks", "Pos", "Box", "Signal", "World", "Level", "Attrs", "Entity", "IntRange",
}

HEADER = """module

{imports}

/-!
# {title}

Generated by `tools/gen/gen_blocks.py` from the Minecraft {version} block dump. Do not edit.
-/

set_option linter.all false
set_option maxRecDepth 100000
set_option maxHeartbeats 0

@[expose] public section

namespace Redstone
"""

FOOTER = "\nend Redstone\n"


def ident(s):
    """A Lean identifier for `s`."""
    if s in KEYWORDS or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", s):
        return "«" + s + "»"
    return s


def camel(s):
    parts = re.split(r"[_\W]+", s)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def lower_first(s):
    return s[:1].lower() + s[1:]


def lean_str(s):
    return json.dumps(s, ensure_ascii=False)


class Gen:
    def __init__(self, dump):
        self.dump = dump
        self.version = dump["version"]
        self.blocks = dump["blocks"]
        self.enum_types = OrderedDict()  # (enumClass, frozenset(values)) -> name
        self.enum_defs = OrderedDict()   # name -> list of values (canonical order)
        self.idx_funs = OrderedDict()    # (type name, tuple(values in property order)) -> fun name
        self.enum_full = {}              # enumClass -> largest value set seen
        self.enum_base = {}              # name of a restricted Direction or Axis type -> which
        self.collect_enums()
        self.build_families()
        self.build_attrs()

    # ---- property types -------------------------------------------------------------------

    def collect_enums(self):
        for b in self.blocks:
            for p in b["properties"]:
                if p["kind"] == "enum":
                    cls = p.get("enumClass", p["name"]).split(".")[-1].split("$")[-1]
                    p["enumClass"] = cls
                    vs = frozenset(p["values"])
                    cur = self.enum_full.get(cls)
                    if cur is None or len(vs) > len(cur):
                        self.enum_full[cls] = vs

    def enum_type(self, p):
        cls = p["enumClass"]
        vs = frozenset(p["values"])
        key = (cls, vs)
        if key in self.enum_types:
            return self.enum_types[key]
        if cls == "Direction" and len(vs) == 6:
            name = "Direction"
        elif cls == "Axis" and len(vs) == 3:
            name = "Axis"
        else:
            name = camel(cls)
            if cls == "Direction" and vs == {"north", "south", "west", "east"}:
                name = "HorizontalDirection"
            elif name in ("Direction", "Axis") or vs != self.enum_full[cls]:
                name = name + "".join(camel(v) for v in p["values"])
            if name in RESERVED_TYPES:
                name += "Value"
            if name in self.enum_defs:
                raise SystemExit(f"enum name clash: {name}")
            self.enum_defs[name] = list(p["values"])
            if cls in ("Direction", "Axis"):
                self.enum_base[name] = cls
        self.enum_types[key] = name
        return name

    def prop_type(self, p):
        """(Lean type, number of values)."""
        k = p["kind"]
        if k == "bool":
            assert p["values"] == ["true", "false"], p
            return "Bool"
        if k == "int":
            vals = [int(v) for v in p["values"]]
            lo, hi = vals[0], vals[-1]
            assert vals == list(range(lo, hi + 1)), p
            return f"(Fin {hi + 1})" if lo == 0 else f"(IntRange {lo} {hi})"
        return self.enum_type(p)

    def idx_expr(self, p, e):
        """Lean expression for the index of the value `e` in the property's own order."""
        k = p["kind"]
        if k == "bool":
            return f"(bif {e} then 0 else 1)"
        if k == "int":
            lo = int(p["values"][0])
            return f"{e}.val" if lo == 0 else f"({e}.val - {lo})"
        t = self.enum_type(p)
        key = (t, tuple(p["values"]))
        if key not in self.idx_funs:
            self.idx_funs[key] = f"{t}.idx{len([k for k in self.idx_funs if k[0] == t])}"
        return f"({self.idx_funs[key]} {e})"

    def parse_expr(self, p, e):
        k = p["kind"]
        if k == "bool":
            return f"parseBool? {e}"
        if k == "int":
            vals = [int(v) for v in p["values"]]
            lo, hi = vals[0], vals[-1]
            return f"parseFin? {hi + 1} {e}" if lo == 0 else f"IntRange.parse? {lo} {hi} {e}"
        t = self.enum_type(p)
        return f"{t}.ofName? {e}"

    def show_expr(self, p, e):
        k = p["kind"]
        if k == "bool":
            return f"(bif {e} then \"true\" else \"false\")"
        if k == "int":
            return f"(toString {e}.val)"
        return f"{e}.name"

    def lit_expr(self, p, value_index):
        v = p["values"][value_index]
        k = p["kind"]
        if k == "bool":
            return v
        if k == "int":
            lo = int(p["values"][0])
            return f"⟨{v}, by decide⟩" if lo == 0 else f"⟨{v}, by decide, by decide⟩"
        return "." + ident(v)

    # ---- families -------------------------------------------------------------------------

    def build_families(self):
        fams = OrderedDict()
        for b in self.blocks:
            b["short"] = b["id"].split(":", 1)[1]
            cls = next(c for c in b["classes"] if c)
            sig = tuple((p["name"], p["kind"], p.get("enumClass"), tuple(p["values"])) for p in b["properties"])
            # Blocks without properties share one family whatever their class: Lean cannot compile
            # an inductive type with more than 245 constructors.
            fams.setdefault((cls, sig) if sig else ("Plain", sig), []).append(b)
        used = defaultdict(int)
        self.families = []
        for (cls, sig), bs in fams.items():
            base = cls[:-5] if cls.endswith("Block") and cls != "Block" else cls
            if not sig:
                cls = "the blocks without properties"
            used[base] += 1
            name = base if used[base] == 1 else f"{base}{used[base]}"
            fam = {
                "name": name,                        # structure name in namespace Blocks
                "ctor": lower_first(name),           # constructor of Block
                "class": cls,
                "classes": bs[0]["classes"],
                "blocks": bs,
                "props": bs[0]["properties"],
                "multi": len(bs) > 1,
            }
            for b in bs:
                b["family"] = fam
            self.families.append(fam)
        for fam in self.families:
            for p in fam["props"]:
                self.prop_type(p)
            # state index: first property most significant
            ns = [len(p["values"]) for p in fam["props"]]
            for b in fam["blocks"]:
                for i, s in enumerate(b["states"]):
                    k = 0
                    for v, n in zip(s["values"], ns):
                        k = k * n + v
                    assert k == i, (b["id"], i, s)

    def state_pattern(self, fam, var="s"):
        return var if fam["props"] else "_"

    # ---- attributes -----------------------------------------------------------------------

    def build_attrs(self):
        self.attr_records = OrderedDict()  # canonical json -> index
        self.tables = OrderedDict()        # tuple of indices -> name
        for b in self.blocks:
            idxs = []
            for s in b["states"]:
                key = json.dumps(s["attrs"], sort_keys=True)
                if key not in self.attr_records:
                    self.attr_records[key] = len(self.attr_records)
                idxs.append(self.attr_records[key])
            b["attr_idxs"] = idxs
        self.attr_bits = max(1, (len(self.attr_records) - 1).bit_length())
        for b in self.blocks:
            idxs = b["attr_idxs"]
            if len(set(idxs)) > 1:
                key = tuple(idxs)
                if key not in self.tables:
                    self.tables[key] = f"attrTable{len(self.tables)}"
                b["attr_table"] = self.tables[key]

    # ---- output ---------------------------------------------------------------------------

    def header(self, title, imports):
        return HEADER.format(title=title, version=self.version,
                             imports="\n".join(f"public import {i}" for i in imports))

    def gen_props(self):
        o = [self.header("Block state property types", ["Redstone.Block.Support"])]
        for name, vals in self.enum_defs.items():
            o.append(f"/-- The values `{'`, `'.join(vals)}`. -/")
            o.append(f"inductive {name}")
            o += [f"  | {ident(v)}" for v in vals]
            o.append("  deriving DecidableEq, Repr\n")
        for name in list(self.enum_defs) + ["Direction", "Axis"]:
            vals = self.enum_defs.get(name) or {
                "Direction": ["down", "up", "north", "south", "west", "east"],
                "Axis": ["x", "y", "z"]}[name]
            o.append(f"/-- The name of the value in block state strings. -/")
            o.append(f"def {name}.name : {name} → String")
            o += [f"  | .{ident(v)} => {lean_str(v)}" for v in vals]
            o.append(f"\n/-- Reads a value from its name. -/")
            o.append(f"def {name}.ofName? : String → Option {name}")
            o += [f"  | {lean_str(v)} => some .{ident(v)}" for v in vals]
            o.append("  | _ => none\n")
        for name, base in self.enum_base.items():
            o.append(f"/-- The value as a `{base}`. -/")
            o.append(f"def {name}.to{base} : {name} → {base}")
            o += [f"  | .{ident(v)} => .{ident(v)}" for v in self.enum_defs[name]]
            o.append("")
        for (t, order), fn in self.idx_funs.items():
            o.append(f"/-- Position of a value in the order `{', '.join(order)}`. -/")
            o.append(f"def {fn} : {t} → ℕ")
            o += [f"  | .{ident(v)} => {i}" for i, v in enumerate(order)]
            o.append("")
        return "\n".join(o) + FOOTER

    def gen_id(self):
        o = [self.header("Block identifiers", ["Redstone.Block.Support"])]
        o.append("/-- Every block of the game, named as in the registry without the `minecraft:` prefix. -/")
        o.append("inductive BlockId")
        o += [f"  | {ident(b['short'])}" for b in self.blocks]
        o.append("  deriving DecidableEq, Repr\n")
        o.append("namespace BlockId\n")
        o.append("/-- The registry name, for example `minecraft:stone`. -/")
        o.append("def name : BlockId → String")
        o += [f"  | .{ident(b['short'])} => {lean_str(b['id'])}" for b in self.blocks]
        o.append("\n/-- Every block id, in registry order. -/")
        o.append("def all : List BlockId := [")
        o.append(",\n".join("  " + ", ".join("." + ident(b["short"]) for b in self.blocks[i:i + 6])
                            for i in range(0, len(self.blocks), 6)))
        o.append("]\n")
        o.append("end BlockId")
        return "\n".join(o) + FOOTER

    def gen_state(self):
        o = [self.header("Blocks and their states",
                         ["Redstone.Block.Generated.Props", "Redstone.Block.Generated.Id"])]
        o.append("namespace Blocks\n")
        for fam in self.families:
            ids = ", ".join(b["short"] for b in fam["blocks"][:4]) + (", ..." if len(fam["blocks"]) > 4 else "")
            if fam["multi"]:
                o.append(f"/-- The blocks of the family `{fam['name']}` ({fam['class']}): {ids}. -/")
                o.append(f"inductive {fam['name']}.Id")
                o += [f"  | {ident(b['short'])}" for b in fam["blocks"]]
                o.append("  deriving DecidableEq, Repr\n")
                o.append(f"/-- The block id as a `BlockId`. -/")
                o.append(f"def {fam['name']}.Id.toBlockId : {fam['name']}.Id → _root_.Redstone.BlockId")
                o += [f"  | .{ident(b['short'])} => .{ident(b['short'])}" for b in fam["blocks"]]
                o.append("")
            if fam["props"]:
                o.append(f"/-- The block state of `{fam['class']}` ({ids}). -/")
                o.append(f"structure {fam['name']} where")
                o += [f"  {ident(p['name'])} : {self.prop_type(p)}" for p in fam["props"]]
                o.append("  deriving DecidableEq, Repr\n")
                o.append("/-- Index of the state among the states of its block, in registry order. -/")
                expr = "0"
                for p in fam["props"]:
                    expr = f"({expr} * {len(p['values'])} + {self.idx_expr(p, 's.' + ident(p['name']))})"
                o.append(f"def {fam['name']}.index (s : {fam['name']}) : ℕ :=\n  {expr}\n")
                o.append("/-- The properties as they appear in a block state string, sorted by name. -/")
                o.append(f"def {fam['name']}.toProps (s : {fam['name']}) : List (String × String) :=")
                o.append("  [" + ", ".join(f"({lean_str(p['name'])}, {self.show_expr(p, 's.' + ident(p['name']))})"
                                           for p in sorted(fam["props"], key=lambda p: p["name"])) + "]\n")
                o.append("/-- Reads the state from its properties. Every property must be present. -/")
                o.append(f"def {fam['name']}.ofProps? (get : String → Option String) : Option {fam['name']} := do")
                for i, p in enumerate(fam["props"]):
                    o.append(f"  let v{i} ← {self.parse_expr(p, '(← get ' + lean_str(p['name']) + ')')}")
                o.append("  pure ⟨" + ", ".join(f"v{i}" for i in range(len(fam["props"]))) + "⟩\n")
        o.append("end Blocks\n")
        o.append("/-- A block state: a block together with the value of each of its properties. One constructor")
        o.append("per Java block class and set of properties, and `plain` for the blocks without properties. -/")
        o.append("inductive Block")
        for fam in self.families:
            args = (f" (id : Blocks.{fam['name']}.Id)" if fam["multi"] else "") + \
                   (f" (s : Blocks.{fam['name']})" if fam["props"] else "")
            o.append(f"  | {ident(fam['ctor'])}{args}")
        o.append("  deriving DecidableEq, Repr\n")
        o.append("namespace Block\n")
        o.append("/-- The block a state belongs to. -/")
        o.append("def id : Block → BlockId")
        for fam in self.families:
            st = " _" if fam["props"] else ""
            if fam["multi"]:
                o.append(f"  | .{ident(fam['ctor'])} i{st} => i.toBlockId")
            else:
                o.append(f"  | .{ident(fam['ctor'])}{st} => .{ident(fam['blocks'][0]['short'])}")
        o.append("\n/-- The properties of a state, sorted by name. -/")
        o.append("def toProps : Block → List (String × String)")
        for fam in self.families:
            i = " _" if fam["multi"] else ""
            if fam["props"]:
                o.append(f"  | .{ident(fam['ctor'])}{i} s => s.toProps")
            else:
                o.append(f"  | .{ident(fam['ctor'])}{i} => []")
        o.append("\n/-- Index of the state among the states of its block, in registry order. -/")
        o.append("def stateIndex : Block → ℕ")
        for fam in self.families:
            i = " _" if fam["multi"] else ""
            if fam["props"]:
                o.append(f"  | .{ident(fam['ctor'])}{i} s => s.index")
            else:
                o.append(f"  | .{ident(fam['ctor'])}{i} => 0")
        o.append("\n/-- Reads a state of the block `id` from its properties. -/")
        o.append("def ofProps? (id : BlockId) (get : String → Option String) : Option Block :=")
        o.append("  match id with")
        for b in self.blocks:
            fam = b["family"]
            c = f".{ident(fam['ctor'])}" + (f" .{ident(b['short'])}" if fam["multi"] else "")
            if fam["props"]:
                o.append(f"  | .{ident(b['short'])} => ({c} ·) <$> Blocks.{fam['name']}.ofProps? get")
            else:
                o.append(f"  | .{ident(b['short'])} => some ({c})")
        o.append("\n/-- The default state of a block. -/")
        o.append("def default : BlockId → Block")
        for b in self.blocks:
            fam = b["family"]
            c = f".{ident(fam['ctor'])}" + (f" .{ident(b['short'])}" if fam["multi"] else "")
            if fam["props"]:
                vals = b["states"][b["default"]]["values"]
                lit = ", ".join(self.lit_expr(p, v) for p, v in zip(fam["props"], vals))
                o.append(f"  | .{ident(b['short'])} => {c} ⟨{lit}⟩")
            else:
                o.append(f"  | .{ident(b['short'])} => {c}")
        o.append("\nend Block")
        return "\n".join(o) + FOOTER

    def attr_lit(self, a):
        def b(k):
            return "true" if a.get(k) else "false"
        fields = [f"air := {b('air')}", f"conductor := {b('conductor')}", f"solid := {b('solid')}",
                  f"solidRender := {b('solidRender')}", f"replaceable := {b('replaceable')}",
                  f"signalSource := {b('signalSource')}", f"analog := {b('analog')}",
                  f"randomlyTicks := {b('randomlyTicks')}", f"hasBlockEntity := {b('hasBlockEntity')}",
                  f"push := .{ident(a['push'])}", f"destroySpeedBits := 0x{a['destroySpeed']}",
                  f"light := {a['light']}", f"sturdyFull := {a['sturdyFull']}",
                  f"sturdyCenter := {a['sturdyCenter']}", f"sturdyRigid := {a['sturdyRigid']}",
                  f"fluid := {lean_str(a.get('fluid') or '')}", f"collision := {a['collision']}",
                  f"outline := {a['outline']}", f"supportShape := {a['supportShape']}"]
        return "{ " + ", ".join(fields) + " }"

    def gen_attrs(self):
        o = [self.header("Block attributes", ["Redstone.Block.Generated.State"])]
        o.append("namespace Block\n")
        recs = [self.attr_lit(json.loads(key)) for key in self.attr_records]

        # The binary search is cut into definitions of three levels each. The Lean kernel
        # evaluates `attrRecord i` by substituting `i` in the body of the definition, which
        # copies every `if` of the body: as one definition that is all 3674 of them for each
        # lookup (2 ms, measured; see docs/proof-feasibility.md), in pieces it is the seven of
        # each of the four definitions on the way. The comparisons are `Nat.blt`, one
        # unfolding away from `Nat.ble`, which the kernel computes natively; `i < n` would go
        # through its `Decidable` instance.
        def tree(lo, hi, depth, indent, body):
            # records lo .. hi - 1
            pad = "  " * indent
            if hi - lo == 1:
                body.append(f"{pad}{recs[lo]}")
            elif depth == 3:
                body.append(f"{pad}{define(lo, hi)} i")
            else:
                mid = (lo + hi) // 2
                body.append(f"{pad}bif i.blt {mid} then")
                tree(lo, mid, depth + 1, indent + 1, body)
                body.append(f"{pad}else")
                tree(mid, hi, depth + 1, indent + 1, body)

        def define(lo, hi):
            name = "attrRecord" if (lo, hi) == (0, len(recs)) else f"attrRecords{lo}To{hi - 1}"
            body = []
            tree(lo, hi, 0, 1, body)
            if name == "attrRecord":
                o.append("/-- The distinct attribute records of the game's block states, found by binary search. -/")
            else:
                o.append(f"/-- The attribute records {lo} to {hi - 1}, for `{lo} ≤ i ≤ {hi - 1}`. -/")
            o.append(f"def {name} (i : ℕ) : Attrs :=")
            o.extend(body)
            o.append("")
            return name
        define(0, len(recs))
        bits = self.attr_bits
        for key, name in self.tables.items():
            n = 0
            for i, v in enumerate(key):
                n |= v << (bits * i)
            o.append(f"def {name} : ℕ := 0x{n:x}")
        o.append("")
        o.append(f"/-- Entry `i` of a packed table. -/\ndef attrLookup (table i : ℕ) : ℕ := (table >>> ({bits} * i)) &&& {(1 << bits) - 1}\n")
        o.append("/-- Which attribute record a state has. -/")
        o.append("def attrIndex : Block → ℕ")
        for fam in self.families:
            st = " s" if fam["props"] else ""

            def rhs(b):
                return f"attrLookup {b['attr_table']} s.index" if "attr_table" in b else str(b["attr_idxs"][0])
            if not fam["multi"]:
                b = fam["blocks"][0]
                stp = st if "attr_table" in b else (" _" if fam["props"] else "")
                o.append(f"  | .{ident(fam['ctor'])}{stp} => {rhs(b)}")
            else:
                groups = OrderedDict()
                for b in fam["blocks"]:
                    groups.setdefault(rhs(b), []).append(b)
                uses_s = any("attr_table" in b for b in fam["blocks"])
                stp = st if uses_s else (" _" if fam["props"] else "")
                if len(groups) == 1:
                    o.append(f"  | .{ident(fam['ctor'])} _{stp} => {next(iter(groups))}")
                else:
                    o.append(f"  | .{ident(fam['ctor'])} i{stp} =>\n    match i with")
                    for r, bs in groups.items():
                        pats = " | ".join("." + ident(b["short"]) for b in bs)
                        o.append(f"    | {pats} => {r}")
        o.append("\n/-- The attributes of a block state, as reported by the server. -/")
        o.append("def attrs (b : Block) : Attrs := attrRecord b.attrIndex\n")
        o.append("end Block")
        return "\n".join(o) + FOOTER


