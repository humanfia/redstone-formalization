#!/usr/bin/env python3
"""Generates `Redstone/Mechanics/Dispatch.lean`: the table from block states to behaviours.

    python3 tools/gen/gen_dispatch.py

Reads `Redstone/Block/Generated/families.json` (written by gen_blocks.py) and
`tools/gen/components.json`. Every component module `Redstone.Component.<M>` must define
`Redstone.Component.<M>.behaviour : Block → Behaviour`.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_blocks import ident  # noqa: E402

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
families = json.load(open(os.path.join(root, "Redstone/Block/Generated/families.json")))
components = json.load(open(os.path.join(root, "tools/gen/components.json")))["components"]


def module_of(classes):
    for c in components:
        if any(k in classes for k in c["classes"]):
            return c["module"]
    return None


o = ["module\n"]
o += [f"public import Redstone.Component.{c['module']}" for c in components]
o += ["public import Redstone.Entity.Item", "public import Redstone.Entity.FallingBlock",
      "public import Redstone.Entity.PrimedTnt", "public import Redstone.Entity.Minecart",
      "public import Redstone.Entity.Projectile", "public import Redstone.Entity.Lightning",
      "public import Redstone.Entity.Hanging", "public import Redstone.Entity.ExperienceOrb",
      "public import Redstone.Entity.Still"]
o.append("""
/-!
# The rules of the game

The table that gives every block state and every entity its behaviour, by sending it to the
component that formalizes it, and the step function of the world under these rules.

The block table is generated by `tools/gen/gen_dispatch.py` from `tools/gen/components.json`,
which lists the Java block classes each component covers. Do not edit it by hand. Blocks of
classes that no component covers are inert.
-/

set_option linter.all false

@[expose] public section

namespace Redstone

/-- The behaviour of a block state. -/
def blockBehaviour (b : Block) : Behaviour :=
  match b with""")
for fam in families:
    args = (" i" if len(fam["blocks"]) > 1 else "") + (" _" if fam["props"] else "")
    if len(fam["blocks"]) > 1 and len({module_of(x["classes"]) for x in fam["blocks"]}) > 1:
        o.append(f"  | .{ident(fam['ctor'])}{args} =>\n    match i with")
        groups = {}
        for x in fam["blocks"]:
            m = module_of(x["classes"])
            if m:
                groups.setdefault(m, []).append(x["id"].split(":")[1])
        for m, ids in groups.items():
            o.append("    | " + " | ".join("." + ident(i) for i in ids) + f" => Component.{m}.behaviour b")
        o.append("    | _ => .inert b")
    else:
        m = module_of(fam["blocks"][0]["classes"])
        args = args.replace(" i", " _")
        o.append(f"  | .{ident(fam['ctor'])}{args} => " + (f"Component.{m}.behaviour b" if m else ".inert b"))
o.append("""
/-- The behaviour of an entity. -/
def entityBehaviour (e : Entity) : EntityBehaviour :=
  match e.data with
  | .item _ => Entity.Item.behaviour
  | .fallingBlock _ => Entity.FallingBlock.behaviour
  | .tnt _ => Entity.PrimedTnt.behaviour
  | .minecart _ _ => Entity.Minecart.behaviour
  | .projectile _ _ => Entity.Projectile.behaviour
  | .lightning _ => Entity.Lightning.behaviour
  | .itemFrame _ _ => Entity.Hanging.behaviour
  | .experienceOrb _ => Entity.ExperienceOrb.behaviour
  | .other _ _ => Entity.Still.behaviour e

/-- The rules of Minecraft, as far as they are formalized. -/
def rules : Rules where
  block := blockBehaviour
  entity := entityBehaviour
  gameEvent := Component.Sculk.onGameEvent

namespace Level

/-- The level after one game tick. -/
def step (l : Level) : Level := rules.step l

/-- The level after `n` game ticks. -/
def steps (n : ℕ) (l : Level) : Level := rules.steps n l

end Level

end Redstone
""")
with open(os.path.join(root, "Redstone/Mechanics/Dispatch.lean"), "w") as f:
    f.write("\n".join(o))
covered = {k for c in components for k in c["classes"]}
print("components:", len(components))
