#!/usr/bin/env python3
"""Generates the item and recipe tables used by the dispenser, dropper and crafter.

    source tools/env.sh && tools/gen/gen_dispenser_data.py

Reads the block dump ($MC_REPORTS/blockdump.json: items and their stack sizes, block names), the
vanilla item component report ($MC_REPORTS/minecraft/components/item), the data pack of the
server ($MC_SRC/data/minecraft: recipes, item tags and block tags) and, for the blocks that
burn, the decompiled `FireBlock` ($MC_SRC/net/minecraft/world/level/block/FireBlock.java). Writes

    Redstone/Component/Dispenser/Items.lean
    Redstone/Component/Crafter/Data.lean

The output is a function of these inputs only.
"""

import glob
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
REPORTS = os.environ.get("MC_REPORTS")
SRC = os.environ.get("MC_SRC")
if not REPORTS or not SRC:
    sys.exit("source tools/env.sh first")
DATA = os.path.join(SRC, "data", "minecraft")


def lean_str(s):
    return json.dumps(s, ensure_ascii=True)


def lean_list(xs, width=96, indent=4):
    """A Lean list literal of strings, wrapped."""
    lines, cur = [], " " * indent + "["
    for i, x in enumerate(xs):
        piece = lean_str(x) + ("," if i + 1 < len(xs) else "]")
        if len(cur) + len(piece) + 1 > width and cur.strip() not in ("", "["):
            lines.append(cur.rstrip())
            cur = " " * (indent + 1) + piece
        else:
            cur += ("" if cur.endswith("[") else " ") + piece
    if not xs:
        cur += "]"
    lines.append(cur)
    return "\n".join(lines)


HEADER = """module

public import Mathlib.Tactic
{imports}
/-!
# {title}

Generated by `tools/gen/gen_dispenser_data.py` from the Minecraft 26.3 server. Do not edit.
-/

set_option linter.all false
set_option maxRecDepth 100000

@[expose] public section

namespace {namespace}
"""

# ---------------------------------------------------------------------------------------------
# Items


def gen_items():
    with open(os.path.join(REPORTS, "blockdump.json")) as f:
        items = json.load(f)["items"]
    ids = sorted(i["id"] for i in items)
    stack = {i["id"]: i["maxStackSize"] for i in items}
    assert set(stack.values()) <= {1, 16, 64}, set(stack.values())
    comps = {}
    for i in ids:
        path = os.path.join(REPORTS, "minecraft", "components", "item", i.split(":")[1] + ".json")
        with open(path) as f:
            comps[i] = json.load(f)["components"]
        assert comps[i].get("minecraft:max_stack_size", 1) == stack[i], i
    tags = Tags()
    out = HEADER.format(imports="", title="Item properties", namespace="Redstone.Component.Dispenser.Items")
    defs = [
        ("equippable", "The items that have the component `minecraft:equippable` by default.",
         [i for i in ids if "minecraft:equippable" in comps[i]]),
        ("sulfurCubeSwallowable", "The item tag `#minecraft:sulfur_cube_swallowable`.",
         sorted(tags.resolve("minecraft:sulfur_cube_swallowable"))),
        ("spawnEggs", "The items that have the component `minecraft:entity_data` by default.",
         [i for i in ids if "minecraft:entity_data" in comps[i]]),
    ]
    blocks = block_ids()
    for tag, name in BLOCK_TAGS:
        xs = block_tag(tag)
        assert set(xs) <= blocks, (tag, set(xs) - blocks)
        defs.append((name, f"The block tag `#minecraft:{tag}`.", xs))
    defs.append(("flammable", "The blocks that fire can spread to: those that `FireBlock.bootStrap` "
                 "gives ignite\nodds (`FireBlock.canBurn`, for a state that is not waterlogged).",
                 flammable(blocks)))
    for name, doc, xs in defs:
        out += f"\n/-- {doc} -/\ndef {name} : List String :=\n{lean_list(xs, indent=2)}\n"
    damage = [(i, comps[i]["minecraft:max_damage"]) for i in ids
              if "minecraft:max_damage" in comps[i]]
    out += ("\n/-- The items that have the component `minecraft:max_damage` by default, with its "
            "value. -/\ndef maxDamage : List (String × ℕ) :=\n  [")
    out += ",\n   ".join(f"({lean_str(i)}, {d})" for i, d in damage) + "]\n"
    out += "\nend Redstone.Component.Dispenser.Items\n"
    write("Redstone/Component/Dispenser/Items.lean", out)
    return ids, comps


# ---------------------------------------------------------------------------------------------
# Blocks the behaviours of the dispenser look at

# The block tags (`BlockTags`) that the behaviours test, with their Lean names.
BLOCK_TAGS = [
    ("candles", "candles"), ("candle_cakes", "candleCakes"), ("campfires", "campfires"),
    ("beehives", "beehives"), ("convertible_to_mud", "convertibleToMud"),
    ("soul_fire_base_blocks", "soulFireBaseBlocks"),
    ("wither_summon_base_blocks", "witherSummonBaseBlocks"), ("copper", "copper"),
]

COLOURS = ["white", "orange", "magenta", "light_blue", "yellow", "lime", "pink", "gray",
           "light_gray", "cyan", "purple", "blue", "brown", "green", "red", "black"]


def block_ids():
    with open(os.path.join(REPORTS, "blockdump.json")) as f:
        return {b["id"] for b in json.load(f)["blocks"]}


def block_tag(name, seen=()):
    """The blocks of the block tag `name` (without `#minecraft:`), in the order of the files."""
    assert name not in seen, name
    with open(os.path.join(DATA, "tags", "block", name + ".json")) as f:
        values = json.load(f)["values"]
    out = []
    for v in values:
        if isinstance(v, dict):
            v = v["id"]
        xs = block_tag(v[1:].split(":")[1], seen + (name,)) if v.startswith("#") else [v]
        out += [x for x in xs if x not in out]
    return out


def flammable(blocks):
    """The blocks registered by `FireBlock.bootStrap` (`setFlammable`), read off the source."""
    path = os.path.join(SRC, "net", "minecraft", "world", "level", "block", "FireBlock.java")
    with open(path) as f:
        lines = [l.strip() for l in f if "setFlammable(" in l and "private void" not in l]
    out = []
    for line in lines:
        m = re.fullmatch(r"fire\.setFlammable\(Blocks\.([A-Z0-9_]+), \d+, \d+\);", line)
        if m:
            names = ["minecraft:" + m.group(1).lower()]
        else:
            m = re.fullmatch(
                r"Blocks\.([A-Z_]+)\.forEach\(block -> fire\.setFlammable\(block, \d+, \d+\)\);",
                line)
            assert m, line
            # A block of every colour: `Blocks.WOOL` holds the blocks `<colour>_wool`, and so on.
            names = [f"minecraft:{c}_{m.group(1).lower()}" for c in COLOURS]
        for n in names:
            assert n in blocks, n
            assert n not in out, n
            out.append(n)
    return sorted(out)


# ---------------------------------------------------------------------------------------------
# Tags and recipes


class Tags:
    def __init__(self):
        self.cache = {}

    def resolve(self, name):
        """The items of the item tag `name` (without `#`), in the order of the tag files."""
        if name in self.cache:
            return self.cache[name]
        path = os.path.join(DATA, "tags", "item", name.split(":")[1] + ".json")
        with open(path) as f:
            values = json.load(f)["values"]
        out = []
        for v in values:
            if isinstance(v, dict):
                v = v["id"]
            for x in (self.resolve(v[1:]) if v.startswith("#") else [v]):
                if x not in out:
                    out.append(x)
        self.cache[name] = out
        return out


def ingredient(j):
    """An ingredient as a list of item ids and `#tag` references."""
    return [j] if isinstance(j, str) else list(j)


def shrink(pattern):
    """`ShapedRecipePattern.shrink`."""
    def first(line):
        i = 0
        while i < len(line) and line[i] == " ":
            i += 1
        return i

    def last(line):
        i = len(line) - 1
        while i >= 0 and line[i] == " ":
            i -= 1
        return i

    left, right, top, bottom = 1 << 30, 0, 0, 0
    for i, line in enumerate(pattern):
        left = min(left, first(line))
        lns = last(line)
        right = max(right, lns)
        if lns < 0:
            if top == i:
                top += 1
            bottom += 1
        else:
            bottom = 0
    if len(pattern) == bottom:
        return []
    return [pattern[i + top][left:right + 1] for i in range(len(pattern) - bottom - top)]


def check_unambiguous(tags, recipes):
    """Fails if two of the recipes could match the same crafting grid (a sufficient test)."""
    def items(ingr):
        out = set()
        for x in ingr:
            out |= set(tags.resolve(x[1:])) if x.startswith("#") else {x}
        return out

    def matchable(sets_a, sets_b):
        # A perfect matching between two lists of item sets, pairing sets that intersect.
        if not sets_a:
            return True
        return any(sets_a[0] & b and matchable(sets_a[1:], sets_b[:k] + sets_b[k + 1:])
                   for k, b in enumerate(sets_b))

    prepared = []
    for name, shaped, width, height, cells, *_ in recipes:
        sets = [items(c) for c in cells]
        prepared.append((name, shaped, width, height, sets, [s for s in sets if s]))
    clashes = []
    for i, (na, sa, wa, ha, ca, fa) in enumerate(prepared):
        for nb, sb, wb, hb, cb, fb in prepared[i + 1:]:
            if len(fa) != len(fb):
                continue
            if sa and sb:
                if (wa, ha) != (wb, hb):
                    continue
                flipped = [cb[(wb - 1 - k % wb) + (k // wb) * wb] for k in range(len(cb))]
                clash = any(all(bool(x) == bool(y) and (not x or x & y) for x, y in zip(ca, other))
                            for other in (cb, flipped))
            else:
                clash = matchable(fa, fb)
            if clash:
                clashes.append((na, nb))
    if clashes:
        sys.exit(f"recipes that may match the same grid: {clashes}")


def gen_recipes(ids, comps):
    tags = Tags()
    used_tags = []

    def ing(j):
        xs = ingredient(j)
        for x in xs:
            if x.startswith("#"):
                if x[1:] not in used_tags:
                    used_tags.append(x[1:])
            else:
                assert x in comps, x
        return xs

    recipes, unmodelled, special = [], [], []
    for path in sorted(glob.glob(os.path.join(DATA, "recipe", "*.json"))):
        name = "minecraft:" + os.path.basename(path)[:-5]
        with open(path) as f:
            d = json.load(f)
        t = d["type"].split(":")[1]
        if not t.startswith("crafting_"):
            continue
        if t == "crafting_shaped":
            rows = shrink(d["pattern"])
            width, height = len(rows[0]), len(rows)
            cells = [[] if c == " " else ing(d["key"][c]) for row in rows for c in row]
            entry = (name, True, width, height, cells)
        elif t == "crafting_shapeless":
            entry = (name, False, 0, 0, [ing(x) for x in d["ingredients"]])
        else:
            # Recipes with their own matching code. Two of them are shaped recipes in disguise;
            # the others are reduced to a necessary condition for a match: the grid holds
            # `count` stacks (0: any number), one item of each of `required`, and nothing
            # outside `allowed`.
            count, required, allowed = 0, None, None
            if t == "crafting_imbue":
                cells = [ing(d["source"] if k == 4 else d["material"]) for k in range(9)]
                unmodelled.append((name, True, 3, 3, cells))
                continue
            elif t == "crafting_decorated_pot":
                cells = [[] for _ in range(9)]
                for k, side in ((1, "back"), (3, "left"), (5, "right"), (7, "front")):
                    cells[k] = ing(d[side])
                unmodelled.append((name, True, 3, 3, cells))
                continue
            elif t == "crafting_special_repairitem":
                # `RepairItemRecipe` looks at components; it is handled in Lean.
                continue
            elif t == "crafting_transmute":
                required = [d["input"], d["material"]]
            elif t == "crafting_dye":
                required = [d["target"], d["dye"]]
            elif t == "crafting_special_bannerduplicate":
                count, required = 2, [d["banner"]]
            elif t == "crafting_special_bookcloning":
                required = [d["source"], d["material"]]
            elif t == "crafting_special_firework_rocket":
                required, allowed = [d["shell"], d["fuel"]], [d["shell"], d["fuel"], d["star"]]
            elif t == "crafting_special_firework_star":
                required = [d["fuel"], d["dye"]]
                allowed = required + [d["trail"], d["twinkle"]] + list(d["shapes"].values())
            elif t == "crafting_special_firework_star_fade":
                required = [d["target"], d["dye"]]
            elif t == "crafting_special_mapextending":
                count, required = 9, [d["map"], d["material"]]
            elif t == "crafting_special_shielddecoration":
                count, required = 2, [d["banner"], d["target"]]
            else:
                sys.exit(f"unknown recipe type {t} in {path}")
            allowed = allowed or required
            special.append((name, count, [ing(g) for g in required],
                            [x for g in allowed for x in ing(g)]))
            continue
        result = d["result"]
        assert set(result) <= {"id", "count", "components"}, result
        assert result["id"] in comps, result
        if "components" in result:
            unmodelled.append(entry)
        else:
            recipes.append(entry + (result["id"], result.get("count", 1)))

    def lists(xss, indent):
        if not xss:
            return "[]"
        pad = " " * indent
        body = (",\n").join(
            pad + " " + ("[]" if not xs else lean_list(xs, indent=indent + 1).lstrip()) for xs in xss)
        return "[\n" + body + "]"

    out = HEADER.format(imports="public import Redstone.Component.Crafter.Recipe\n",
                        title="Crafting recipes and item tags",
                        namespace="Redstone.Component.Crafter.Data")
    out += "\n/-- The item tags that recipes refer to, with their items. -/\n"
    out += "def tags : List (String × List String) := [\n"
    out += ",\n".join(
        f"  ({lean_str('#' + t)},\n{lean_list(tags.resolve(t), indent=4)})" for t in used_tags)
    out += "]\n"

    def recipe_term(e):
        name, shaped, width, height, cells = e[:5]
        result = f"{lean_str(e[5])}, {e[6]}" if len(e) > 5 else '"", 0'
        return (f"  ⟨{lean_str(name)}, {'true' if shaped else 'false'}, {width}, {height}, "
                f"{lists(cells, 4)},\n    {result}⟩")

    def chunks(name, doc, entries):
        nonlocal out
        size, parts = 60, []
        for k in range(0, max(len(entries), 1), size):
            part = f"{name}{k // size}"
            parts.append(part)
            out += f"\n/-- Part of `{name}`. -/\ndef {part} : List Recipe := [\n"
            out += ",\n".join(recipe_term(e) for e in entries[k:k + size]) + "]\n"
        out += (f"\n/-- {doc} -/\ndef {name} : List Recipe :=\n  List.flatten [\n    "
                + ",\n    ".join(parts) + "]\n")

    chunks("recipes", "The shaped and shapeless crafting recipes whose result is a plain stack.",
           recipes)
    chunks("unmodelled", "The crafting recipes whose result has components or depends on the "
           "input:\nsuspicious stew, tipped arrows and decorated pots.", unmodelled)
    check_unambiguous(tags, recipes)
    out += ("\n/-- The crafting recipes with their own matching code (dyeing, fireworks, ...), "
            "except item\nrepair, reduced to a necessary condition for a match. -/\n"
            "def special : List SpecialRecipe := [\n")
    out += ",\n".join(f"  ⟨{lean_str(n)}, {c}, {lists(g, 4)},\n{lean_list(a, indent=4)}⟩"
                      for n, c, g, a in special) + "]\n"
    damageable = [i for i in ids if "minecraft:max_damage" in comps[i]]
    out += ("\n/-- The items that have the component `minecraft:max_damage` by default. -/\n"
            f"def damageable : List String :=\n{lean_list(damageable, indent=2)}\n")
    out += "\nend Redstone.Component.Crafter.Data\n"
    write("Redstone/Component/Crafter/Data.lean", out)
    print(f"{len(recipes)} recipes, {len(unmodelled)} unmodelled, {len(special)} special, "
          f"{len(used_tags)} tags")


def write(rel, text):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    for line in text.split("\n"):
        assert len(line) <= 100, line
    with open(path, "w") as f:
        f.write(text)
    print("wrote", rel)


if __name__ == "__main__":
    ids, comps = gen_items()
    gen_recipes(ids, comps)
