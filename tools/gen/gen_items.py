#!/usr/bin/env python3
"""Generates the Lean tables about fuels and cooking recipes that the containers need.

    python3 tools/gen/gen_items.py $MC_REPORTS/blockdump.json $MC_SRC \\
        Redstone/Component/CookingTable.lean

The maximal stack sizes of the items are not here: the one table of them is
`Redstone.itemMaxStackSize` (`Redstone/Block/Generated/Items.lean`, by `gen_blocks.py`).

Sources:

* the cooking recipes: the recipe files of the server's built-in data pack
  (`data/minecraft/recipe/*.json`, types `smelting`, `blasting`, `smoking`), with the item tags
  of `data/minecraft/tags/item`; the name of a recipe and the experience it gives are in the
  tables `*Experience`, apart from the tables `*Recipes`;
* the fuels: the item registrations in the decompiled `Items.java` (`cookingFuel(...)`,
  `brewingFuel(...)`, `craftRemainder(...)`) and the providers they name, under
  `data/minecraft/context_int_provider`.

The fuel table comes from reading decompiled code, so it is checked against the server item by
item by the scenarios `tests/scenarios/hopper/table-*.json`, which burn every item of the game
in every kind of furnace.
"""
import json
import os
import re
import struct
import sys

HEADER = """module

public import {imp}

/-!
# {title}

Generated by `tools/gen/gen_items.py` from the Minecraft 26.3 server. Do not edit.
-/

set_option linter.all false
set_option maxRecDepth 100000
set_option maxHeartbeats 0

@[expose] public section

namespace Redstone.Item

"""

FOOTER = "\nend Redstone.Item\n"

COLORS = ["white", "orange", "magenta", "light_blue", "yellow", "lime", "pink", "gray",
          "light_gray", "cyan", "purple", "blue", "brown", "green", "red", "black"]


def lean_str(s):
    return json.dumps(s)


def string_list(name, doc, values, per_line=2):
    out = [f"/-- {doc} -/", f"def {name} : List String := ["]
    rows = [values[i:i + per_line] for i in range(0, len(values), per_line)]
    out += ["  " + ", ".join(lean_str(v) for v in row) + ("," if i + 1 < len(rows) else "")
            for i, row in enumerate(rows)]
    out.append("]")
    return "\n".join(out) + "\n"


def load_tags(src):
    root = os.path.join(src, "data/minecraft/tags/item")
    raw = {}
    for dirpath, _, files in os.walk(root):
        for f in files:
            if f.endswith(".json"):
                rel = os.path.relpath(os.path.join(dirpath, f), root)[:-5]
                raw["minecraft:" + rel.replace(os.sep, "/")] = json.load(
                    open(os.path.join(dirpath, f)))["values"]

    def resolve(tag, seen=()):
        assert tag not in seen, tag
        out = []
        for v in raw[tag]:
            if isinstance(v, dict):
                v = v["id"]
            if v.startswith("#"):
                out += resolve(v[1:], seen + (tag,))
            else:
                out.append(v)
        return out

    return {t: resolve(t) for t in raw}


def ingredient_items(ing, tags):
    if isinstance(ing, list):
        return [x for i in ing for x in ingredient_items(i, tags)]
    if ing.startswith("#"):
        return tags[ing[1:]]
    return [ing]


def load_recipes(src, tags):
    """type -> [(recipe id, ingredient items, result id, result count, cooking time,
    experience)], in the order of the recipe ids."""
    root = os.path.join(src, "data/minecraft/recipe")
    out = {"smelting": [], "blasting": [], "smoking": []}
    for f in sorted(os.listdir(root)):
        if not f.endswith(".json"):
            continue
        r = json.load(open(os.path.join(root, f)))
        kind = r["type"].removeprefix("minecraft:")
        if kind not in out:
            continue
        result = r["result"]
        assert set(result) <= {"id", "count"}, (f, result)
        out[kind].append((f[:-5], ingredient_items(r["ingredient"], tags), result["id"],
                          result.get("count", 1), r["cookingtime"], r.get("experience", 0.0)))
    return out


def load_brewing(src, tags):
    """The reagents and the potion inputs of the brewing recipes. Every recipe asks for potion
    contents, so no recipe accepts a stack without components; the model relies on this."""
    root = os.path.join(src, "data/minecraft/recipe/brewing")
    reagents, inputs = set(), set(tags["minecraft:brewing_potion_inputs"])
    for f in sorted(os.listdir(root)):
        r = json.load(open(os.path.join(root, f)))
        assert r["type"] == "minecraft:brewing" and "potion_contents" in r["input"], f
        reagents.update(ingredient_items(r["reagent"]["item"], tags))
        inputs.update(ingredient_items(r["input"]["item"], tags))
    return reagents, inputs


def id_constants(src, cls):
    """The string constants of `ItemIds` / `BlockItemIds`: constant name -> item id."""
    text = open(os.path.join(src, "net/minecraft/references", cls + ".java")).read()
    out = {}
    for name, arg in re.findall(r"(\w+) = (?:\w+\.)?create\(\"([a-z0-9_]+)\"\)", text):
        out[name] = "minecraft:" + arg
    return out


def provider_value(src, key):
    """The value of a `context_int_provider`: (normal, fast)."""
    path = os.path.join(src, "data/minecraft/context_int_provider", key + ".json")

    def ev(v, fast):
        if isinstance(v, int):
            return v
        if isinstance(v, str):
            return ev(json.load(open(os.path.join(
                src, "data/minecraft/context_int_provider",
                v.removeprefix("minecraft:") + ".json"))), fast)
        if v["type"] == "minecraft:div":
            return ev(v["left"], fast) // ev(v["right"], fast)
        if v["type"] == "minecraft:conditional":
            assert v["condition"] == "minecraft:block/fast_cooking", v
            return ev(v["on_true"] if fast else v["on_false"], fast)
        raise ValueError(v)

    v = json.load(open(path))
    return ev(v, False), ev(v, True)


def load_fuels(src, dump):
    """item id -> provider constant, for `cookingFuel`; plus brewing fuels and remainders."""
    text = open(os.path.join(src, "net/minecraft/world/item/Items.java")).read()
    consts = {}
    for cls in ("ItemIds", "BlockItemIds"):
        for k, v in id_constants(src, cls).items():
            consts[cls + "." + k] = v
    known = {i["id"] for i in dump["items"]}
    fuels, brewing, remainders = {}, {}, {}
    field_ids = {}
    colored = {}
    for cls in ("ItemIds", "BlockItemIds"):
        for k, v in re.findall(
                r"(\w+) = createSimpleColored\(\"([a-z0-9_]+)\"\)",
                open(os.path.join(src, "net/minecraft/references", cls + ".java")).read()):
            colored[cls + "." + k] = v
    for st in re.split(r"\n   public static final ", text)[1:]:
        kind, field = st.split(" ", 2)[:2]
        st = st.split(";\n")[0]
        if kind == "Item":
            m = re.search(r"\b((?:Block)?ItemIds\.\w+)", st)
            item = consts.get(m.group(1)) if m else None
            if item is None:
                # `registerBlock(Blocks.X)`: the item has the id of the block.
                m = re.search(r"registerBlock\(\s*Blocks\.(\w+)", st)
                item = "minecraft:" + m.group(1).lower() if m else None
            items = [item]
            if item is not None:
                field_ids[field] = item
        elif kind == "ColorCollection<Item>":
            m = re.search(r"\b((?:Block)?ItemIds\.\w+)", st)
            items = [f"minecraft:{c}_{colored[m.group(1)]}" for c in COLORS] if m else [None]
        else:
            items = [None]
        for name, table in (("cookingFuel", fuels), ("brewingFuel", brewing)):
            m = re.search(name + r"\(ContextIntProviders\.(\w+)\)", st)
            if m:
                for item in items:
                    assert item in known, (field, item)
                    table[item] = m.group(1)
        m = re.search(r"craftRemainder\((\w+)\)", st)
        if m:
            for item in items:
                assert item in known, (field, item)
                remainders[item] = m.group(1)
    remainders = {k: field_ids[v] for k, v in remainders.items()}
    provider_text = open(os.path.join(
        src, "net/minecraft/world/level/storage/loot/providers/number/ints",
        "ContextIntProviders.java")).read()
    keys = dict(re.findall(r"(\w+) = createKey\(\"([a-z0-9_/]+)\"\)", provider_text))
    fuels = {k: provider_value(src, keys[v]) for k, v in fuels.items()}
    brewing = {k: provider_value(src, keys[v])[0] for k, v in brewing.items()}
    return fuels, brewing, remainders


def gen_cooking_table(dump, src):
    tags = load_tags(src)
    recipes = load_recipes(src, tags)
    fuels, brewing, remainders = load_fuels(src, dump)
    order = [i["id"] for i in dump["items"]]
    out = HEADER.format(imp="Mathlib.Tactic", title="Fuels and cooking recipes")
    out += ("/-- The furnace fuels (the items with the component `minecraft:cooking_fuel`), with\n"
            "their burn time in a furnace and in a blast furnace or smoker. -/\n"
            "def cookingFuels : List (String × ℕ × ℕ) := [\n")
    rows = [f"  ({lean_str(i)}, {fuels[i][0]}, {fuels[i][1]})" for i in order if i in fuels]
    out += ",\n".join(rows) + "\n]\n\n"
    out += ("/-- The brewing fuels (the items with the component `minecraft:brewing_fuel`), with\n"
            "the number of brews one item pays for. -/\n"
            "def brewingFuels : List (String × ℕ) := [\n")
    out += ",\n".join(f"  ({lean_str(i)}, {brewing[i]})" for i in order if i in brewing)
    out += "\n]\n\n"
    out += ("/-- `Item.getCraftingRemainder()`: what is left of an item that was used up. -/\n"
            "def craftingRemainders : List (String × String) := [\n")
    out += ",\n".join(f"  ({lean_str(i)}, {lean_str(remainders[i])})"
                      for i in order if i in remainders)
    out += "\n]\n\n"
    reagents, inputs = load_brewing(src, tags)
    out += string_list(
        "brewingReagents",
        "The property set `minecraft:brewing_reagent`: the reagents of the brewing recipes.",
        [i for i in order if i in reagents], 2) + "\n"
    out += string_list(
        "brewingPotionInputs",
        "`PotionIngredient.isPotionInput`: the inputs of the brewing recipes (the property set\n"
        "`minecraft:brewing_input`) and the item tag `minecraft:brewing_potion_inputs`.",
        [i for i in order if i in inputs], 2) + "\n"
    out += string_list(
        "furnaceFuelBottomTakeable",
        "The item tag `minecraft:furnace_fuel_bottom_takeable`: what a hopper may take out of\n"
        "the fuel slot of a furnace.",
        tags["minecraft:furnace_fuel_bottom_takeable"], 2) + "\n"
    for kind in ("smelting", "blasting", "smoking"):
        table = {}
        for rid, items, result, count, time, experience in recipes[kind]:
            for item in items:
                # No item has two recipes of one type, so the order of the lookup is irrelevant.
                assert item not in table, (rid, item)
                table[item] = (result, count, time, rid, experience)
        out += (f"/-- The recipes of type `minecraft:{kind}`: ingredient, result, number of\n"
                "results, cooking time. -/\n"
                f"def {kind}Recipes : List (String × String × ℕ × ℕ) := [\n")
        out += ",\n".join(
            f"  ({lean_str(i)}, {lean_str(table[i][0])}, {table[i][1]}, {table[i][2]})"
            for i in order if i in table)
        out += "\n]\n\n"
        float_bits = lambda v: struct.unpack("<I", struct.pack("<f", v))[0]
        out += (f"/-- The recipes of type `minecraft:{kind}`: ingredient, name of the recipe\n"
                "(the key under which a furnace counts it in `RecipesUsed`) and the experience\n"
                "one use of it gives, as the bits of a `float`. -/\n"
                f"def {kind}Experience : List (String × String × ℕ) := [\n")
        out += ",\n".join(
            f"  ({lean_str(i)}, {lean_str('minecraft:' + table[i][3])}, "
            f"0x{float_bits(table[i][4]):08x})"
            for i in order if i in table)
        out += "\n]\n\n"
    return out.rstrip("\n") + "\n" + FOOTER


def main():
    dump_path, src, cooking_out = sys.argv[1:4]
    dump = json.load(open(dump_path))
    open(cooking_out, "w").write(gen_cooking_table(dump, src))


if __name__ == "__main__":
    main()
