#!/usr/bin/env python3
"""Generates `Redstone/Block/Generated/Tags.lean`: block tags and block classes as predicates.

    python3 tools/gen/gen_tags.py [server.jar]

The block tags are read from the server jar (`data/minecraft/tags/block/<name>.json`, with the
tags they refer to expanded); the jar defaults to
`$MC_HOME/bundle/META-INF/versions/<version>/server-<version>.jar`. The classes are read from the
class chains in `Redstone/Block/Generated/families.json` (written by gen_blocks.py).

To make another tag or class available to the Lean code, add its name to `TAGS` or `CLASSES`
below and run the script again.
"""
import glob
import json
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_blocks import ident  # noqa: E402

# The block tags (`BlockTags`) the components use.
TAGS = [
    "fences", "wooden_fences", "walls", "wall_post_override", "shulker_boxes",
    "cannot_support_snow_layer", "support_override_snow_layer",
    "supports_vegetation", "supports_dry_vegetation", "supports_azalea", "supports_wither_rose",
    "supports_warped_fungus", "supports_crimson_fungus", "supports_warped_roots",
    "supports_crimson_roots", "supports_nether_sprouts", "supports_nether_wart",
    "supports_pumpkin_stem", "supports_melon_stem", "supports_mangrove_propagule",
    "supports_hanging_mangrove_propagule", "supports_small_dripleaf", "supports_lily_pad",
    "support_override_cactus_flower", "cannot_support_seagrass",
]

# The Java block classes for which `state.getBlock() instanceof C` is needed.
CLASSES = ["LeavesBlock", "FenceGateBlock", "IronBarsBlock", "CarpetBlock", "VegetationBlock",
           "MushroomBlock"]

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")


def find_jar():
    if len(sys.argv) > 1:
        return sys.argv[1]
    home = os.environ.get("MC_HOME")
    if not home:
        sys.exit("give the server jar as an argument or set MC_HOME")
    jars = sorted(glob.glob(os.path.join(home, "bundle/META-INF/versions/*/server-*.jar")))
    if not jars:
        sys.exit(f"no server jar under {home}/bundle/META-INF/versions")
    return jars[-1]


def resolve(jar, name, seen=()):
    """The blocks of a tag, in the order of the tag file, without the `minecraft:` prefix."""
    if name in seen:
        sys.exit(f"tag {name} refers to itself")
    out = []
    for v in json.loads(jar.read(f"data/minecraft/tags/block/{name}.json"))["values"]:
        if isinstance(v, dict):  # {"id": ..., "required": false}
            v = v["id"]
        ns, _, rest = v.lstrip("#").partition(":")
        if ns != "minecraft":
            sys.exit(f"tag {name}: unexpected namespace in {v}")
        for b in resolve(jar, rest, seen + (name,)) if v.startswith("#") else [rest]:
            if b not in out:
                out.append(b)
    return out


def predicate(doc, name, blocks, known):
    unknown = [b for b in blocks if b not in known]
    if unknown:
        sys.exit(f"{name}: not in the block inventory: {unknown}")
    o = [f"/-- {doc} -/", f"def {ident(name)} : BlockId → Bool"]
    if blocks:
        line = "  |"
        for i, b in enumerate(blocks):
            piece = f" .{ident(b)}" + (" |" if i + 1 < len(blocks) else " => true")
            if len(line) + len(piece) > 100:
                o.append(line)
                line = "  " + piece
            else:
                line += piece
        o.append(line)
    o.append("  | _ => false\n")
    return o


families = json.load(open(os.path.join(root, "Redstone/Block/Generated/families.json")))
blocks = [b for fam in families for b in fam["blocks"]]
known = {b["id"].split(":")[1] for b in blocks}
jar_path = find_jar()
version = os.path.basename(jar_path)[len("server-"):-len(".jar")]

o = [f"""module

public import Redstone.Block.Generated.Id

/-!
# Block tags and block classes

Generated by `tools/gen/gen_tags.py` from the block tags of the Minecraft {version} server jar and
the class chains of the block dump. Do not edit.
-/

set_option linter.all false

@[expose] public section

namespace Redstone

/-! ### Block tags

The block tags (`BlockTags`), as predicates on blocks: `BlockTag.t id` is
`state.is(BlockTags.T)` for a state of the block `id`. -/

namespace BlockTag
"""]
with zipfile.ZipFile(jar_path) as jar:
    for t in TAGS:
        o += predicate(f"The block tag `minecraft:{t}`.", t, resolve(jar, t), known)
o.append("""end BlockTag

/-! ### Block classes

The Java classes of blocks, as predicates on blocks: `BlockClass.c id` is
`state.getBlock() instanceof C` for a state of the block `id`. -/

namespace BlockClass
""")
for c in CLASSES:
    members = [b["id"].split(":")[1] for b in blocks if c in b["classes"]]
    if not members:
        sys.exit(f"no block of class {c}")
    o += predicate(f"The blocks of class `{c}`.", c[:1].lower() + c[1:], members, known)
o.append("end BlockClass\n\nend Redstone\n")
with open(os.path.join(root, "Redstone/Block/Generated/Tags.lean"), "w") as f:
    f.write("\n".join(o))
print("tags:", len(TAGS), "classes:", len(CLASSES))
