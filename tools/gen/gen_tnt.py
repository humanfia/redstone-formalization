def lean_id(block_id):
    return "." + ident(block_id.split(":", 1)[1])


def tag(tags_dir, name, seen=None):
    """The block ids of a block tag, with nested tags resolved."""
    out = []
    with open(os.path.join(tags_dir, name + ".json")) as f:
        for v in json.load(f)["values"]:
            v = v["id"] if isinstance(v, dict) else v
            if v.startswith("#"):
                out += tag(tags_dir, v.split(":", 1)[1])
            else:
                out.append(v)
    return out


def by_value(o, name, doc, typ, of_bits, blocks, key):
    """A function `BlockId → typ` written as a match grouped by value."""
    count = Counter(b[key] for b in blocks)
    default = count.most_common(1)[0][0]
    o.append(f"/-- {doc} -/")
    o.append(f"def {name} : BlockId → {typ}")
    for value in sorted(count):
        if value == default:
            continue
        ids = [lean_id(b["id"]) for b in blocks if b[key] == value]
        line = "  |"
        for i in ids:
            if len(line) + len(i) + 3 > 100:
                o.append(line[:-2])
                line = "  |"
            line += " " + i + " |"
        o.append(line[:-2] + f" => {of_bits} 0x{value}")
    o.append(f"  | _ => {of_bits} 0x{default}")
    o.append("")


def predicate(o, name, doc, ids, known):
    o.append(f"/-- {doc} -/")
    o.append(f"def {name} : BlockId → Bool")
    line = "  |"
    for i in [lean_id(i) for i in ids if i in known]:
        if len(line) + len(i) + 3 > 100:
            o.append(line[:-2])
            line = "  |"
        line += " " + i + " |"
    o.append(line[:-2] + " => true")
    o.append("  | _ => false")
    o.append("")


