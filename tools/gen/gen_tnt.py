class Unknown(Exception):
    """The drops depend on something the model does not have (chance, a block entity, ...)."""


def loot_condition(c, block_id, props):
    """A loot condition for a block destroyed by an explosion without drop decay: no tool, no
    explosion radius, and the exploding entity as `this`."""
    if isinstance(c, list):
        return all(loot_condition(x, block_id, props) for x in c)
    if isinstance(c, str):
        if c.startswith("minecraft:tool/"):
            return False  # a predicate on the tool, which is the empty stack
        raise Unknown(c)
    t = c["type"].split(":", 1)[1]
    if t == "survives_explosion":
        return True
    if t == "match_tool":
        return False
    if t == "entity_properties":
        if c["entity"] == "this" and c["predicate"] == {}:
            return THIS_ENTITY[0]  # any entity passes, none fails
        raise Unknown(t)
    if t == "match_block":
        blocks = c["blocks"]
        if isinstance(blocks, str):
            blocks = [blocks]
        if any(b.startswith("#") for b in blocks):
            raise Unknown(t)
        if block_id not in blocks:
            return False
        for k, v in c.get("state", {}).items():
            if isinstance(v, dict):
                value = int(props[k])
                if ("min" in v and value < int(v["min"])) or ("max" in v and value > int(v["max"])):
                    return False
            elif props.get(k) != str(v).lower():
                return False
        return True
    if t == "inverted":
        return not loot_condition(c["term"], block_id, props)
    if t == "all_of":
        return all(loot_condition(x, block_id, props) for x in c["terms"])
    if t == "any_of":
        return any(loot_condition(x, block_id, props) for x in c["terms"])
    raise Unknown(t)  # table_bonus, random_chance, location_check


def loot_modify(stack, modifiers, block_id, props):
    """Applies item functions to a stack `[item, count]`."""
    for m in [modifiers] if isinstance(modifiers, dict) else modifiers:
        if "condition" in m and not loot_condition(m["condition"], block_id, props):
            continue
        t = m["type"].split(":", 1)[1]
        if t == "explosion_decay":
            pass  # no explosion radius without drop decay
        elif t == "set_count":
            if not isinstance(m["count"], (int, float)) or m["count"] != int(m["count"]):
                raise Unknown("count")
            stack[1] = (stack[1] if m.get("add") else 0) + int(m["count"])
        elif t == "apply_bonus":
            # the enchantment level is 0: `ore_drops` and `uniform_bonus_count` change nothing
            if m["formula"].split(":", 1)[1] not in ("ore_drops", "uniform_bonus_count"):
                raise Unknown(m["formula"])
        elif t == "limit_count":
            limit = m["limit"]
            if not isinstance(limit, dict) or not all(isinstance(v, int) for v in limit.values()):
                raise Unknown(t)
            stack[1] = max(stack[1], limit.get("min", stack[1]))
            stack[1] = min(stack[1], limit.get("max", stack[1]))
        elif t == "copy_components" and set(m["include"]) <= {"minecraft:custom_name"}:
            pass  # custom names are not modelled: no block entity has one
        else:
            raise Unknown(t)  # copy_components, copy_state


def loot_expand(entry, block_id, props):
    """The entries a pool entry expands to, or None when its condition fails."""
    if "condition" in entry and not loot_condition(entry["condition"], block_id, props):
        return None
    t = entry["type"].split(":", 1)[1]
    if t == "item":
        if entry.get("weight", 1) != 1:
            raise Unknown("weight")
        return [entry]
    if t == "alternatives":
        for child in entry["children"]:
            expanded = loot_expand(child, block_id, props)
            if expanded is not None:
                return expanded
        return None
    raise Unknown(t)  # dynamic


def loot_drops(table, block_id, props, max_stack):
    """The stacks `BlockState.getDrops` returns for an explosion, as (item, count)."""
    out = []
    for pool in table.get("pools", []):
        if "condition" in pool and not loot_condition(pool["condition"], block_id, props):
            continue
        if not isinstance(pool["rolls"], (int, float)) or pool.get("bonus_rolls", 0) != 0:
            raise Unknown("rolls")
        for _ in range(int(pool["rolls"])):
            valid = []
            for entry in pool["entries"]:
                valid += loot_expand(entry, block_id, props) or []
            if len(valid) > 1:
                raise Unknown("choice")
            for entry in valid:
                stack = [entry["name"], 1]
                loot_modify(stack, entry.get("modifier", []), block_id, props)
                loot_modify(stack, pool.get("modifier", []), block_id, props)
                loot_modify(stack, table.get("modifier", []), block_id, props)
                # `LootTable.createStackSplitter`
                size = max_stack[stack[0]]
                if stack[1] < size:
                    out.append((stack[0], stack[1]))
                else:
                    count = stack[1]
                    while count > 0:
                        out.append((stack[0], min(size, count)))
                        count -= min(size, count)
    return out


def threshold(p):
    """The least `n` with `p <= n / 2 ** 24` for the `float` `p`: a draw `nextFloat()`, which is
    a multiple of `2 ** -24`, is below `p` exactly when its numerator is below `n`."""
    if not isinstance(p, (int, float)):
        raise Unknown("chance")
    exact = Fraction(struct.unpack("f", struct.pack("f", p))[0]) * 2 ** 24
    return -((-exact.numerator) // exact.denominator)


def chance_conditions(c, block_id, props):
    """The conditions `c` of an entry, tested in order: False when one that does not depend on
    chance fails before any draw, else the thresholds of those that draw."""
    if isinstance(c, list):
        terms = c
    elif isinstance(c, dict) and c["type"] == "minecraft:all_of":
        terms = c["terms"]
    else:
        terms = [c]
    out = []
    for term in terms:
        t = term["type"].split(":", 1)[1] if isinstance(term, dict) else None
        if t == "all_of":
            inner = chance_conditions(term, block_id, props)
            if inner is False:
                if out:
                    raise Unknown("a condition that fails after a draw")
                return False
            out += inner
        elif t == "random_chance":
            out.append(threshold(term["chance"]))
        elif t == "table_bonus":
            # the enchantment level of the empty tool is 0
            out.append(threshold(term["chances"][0]))
        elif not loot_condition(term, block_id, props):
            if out:
                raise Unknown("a condition that fails after a draw")
            return False
    return out


def integer(v):
    if not isinstance(v, (int, float)) or v != int(v):
        raise Unknown("number")
    return int(v)


def lean_int(v):
    return str(v) if v >= 0 else f"({v})"


def chance_number(n):
    """A number provider as a `LootNumber`, and whether it draws."""
    if isinstance(n, (int, float)):
        return f".const {lean_int(integer(n))}", False
    t = n["type"].split(":", 1)[1]
    if t == "constant":
        return f".const {lean_int(integer(n['value']))}", False
    if t == "uniform":
        lo, hi = integer(n["min"]), integer(n["max"])
        return f".uniform {lean_int(lo)} {lean_int(hi)}", lo < hi
    if t == "binomial":
        return f".binomial {integer(n['n'])} {threshold(n['p'])}", True
    raise Unknown(t)


def chance_functions(modifiers, block_id, props):
    """Item functions as `LootFunction`s, and whether one of them draws."""
    out, draws = [], False
    for m in [modifiers] if isinstance(modifiers, dict) else modifiers:
        # a condition that depends on chance raises `Unknown`
        if "condition" in m and not loot_condition(m["condition"], block_id, props):
            continue
        t = m["type"].split(":", 1)[1]
        if t == "explosion_decay":
            pass  # no explosion radius
        elif t == "set_count":
            number, d = chance_number(m["count"])
            out.append(f".setCount {'true' if m.get('add') else 'false'} ({number})")
            draws |= d
        elif t == "apply_bonus":
            # the tool is the empty stack, so the enchantment level is 0
            formula = m["formula"].split(":", 1)[1]
            if formula == "uniform_bonus_count":
                out.append(".uniformBonus")  # `nextInt(1)`: a draw that adds nothing
                draws = True
            elif formula == "binomial_with_bonus_count":
                params = m["parameters"]
                out.append(f".binomialBonus {integer(params['extra'])} "
                           f"{threshold(params['probability'])}")
                draws = True
            elif formula != "ore_drops":  # which changes nothing and draws nothing at level 0
                raise Unknown(formula)
        elif t == "limit_count":
            limit = m["limit"]
            if not isinstance(limit, dict) or not all(isinstance(v, int) for v in limit.values()):
                raise Unknown(t)
            bound = lambda k: f"(some {lean_int(limit[k])})" if k in limit else "none"
            out.append(f".limit {bound('min')} {bound('max')}")
        elif t == "copy_components" and set(m["include"]) <= {"minecraft:custom_name"}:
            pass
        else:
            raise Unknown(t)
    return out, draws


def chance_expand(entry, block_id, props):
    """The item entries an entry may expand to, in the order in which they are tried, each with
    the thresholds of its conditions: the first whose conditions hold is the one."""
    t = entry["type"].split(":", 1)[1]
    if t == "item":
        chances = chance_conditions(entry.get("condition", []), block_id, props)
        if chances is False:
            return []
        if entry.get("weight", 1) != 1:
            raise Unknown("weight")
        return [(chances, entry)]
    if t == "alternatives":
        # a condition that depends on chance raises `Unknown`
        if "condition" in entry and not loot_condition(entry["condition"], block_id, props):
            return []
        out = []
        for child in entry["children"]:
            out += chance_expand(child, block_id, props)
            if out and out[-1][0] == []:
                break  # this one always holds: the rest is never reached
        return out
    raise Unknown(t)


def loot_chance(table, block_id, props, max_stack):
    """The loot of a broken block as a `ChanceLoot`, or None when it draws nothing from the
    table's random sequence."""
    pools, draws = [], False
    for pool in table.get("pools", []):
        # a condition that depends on chance raises `Unknown`
        if "condition" in pool and not loot_condition(pool["condition"], block_id, props):
            continue
        if not isinstance(pool["rolls"], (int, float)) or pool.get("bonus_rolls", 0) != 0:
            raise Unknown("rolls")
        expanded = [e for e in (chance_expand(entry, block_id, props) for entry in pool["entries"])
                    if e]
        if len(expanded) > 1:
            raise Unknown("choice")  # a weighted choice among the entries that hold
        if not expanded or integer(pool["rolls"]) == 0:
            continue
        items = []
        for chances, entry in expanded[0]:
            functions = []
            for modifiers in (entry.get("modifier", []), pool.get("modifier", []),
                              table.get("modifier", [])):
                fs, d = chance_functions(modifiers, block_id, props)
                functions += fs
                draws |= d
            draws |= bool(chances)
            items.append(f"⟨[{', '.join(map(str, chances))}], [{', '.join(functions)}], "
                         f"{max_stack[entry['name']]}⟩")
        pools.append(f"⟨{integer(pool['rolls'])}, [{', '.join(items)}]⟩")
    if not draws:
        return None
    key = table["random_sequence"]
    digest = hashlib.md5(key.encode()).digest()  # `RandomSupport.seedFromHashOf`
    return (f"⟨{json.dumps(key)}, 0x{digest[:8].hex()}, 0x{digest[8:].hex()}, "
            f"[{', '.join(pools)}]⟩")


def match_arms(o, ids):
    """Writes the alternatives `| .a | .b` of a match arm, wrapped; the last line is returned."""
    line = "  |"
    for i in ids:
        if len(line) + len(i) + 3 > 100:
            o.append(line[:-2])
            line = "  |"
        line += " " + i + " |"
    return line[:-2]


def drops_table(o, dump, tnt, loot_dir, mode):
    """`explosionDrops : Block → Option (List (String × ℕ))` (mode `explosion`),
    `brokenDropStacks : Block → Option ℕ` (mode `broken`) or
    `brokenChanceLoot : Block → Option ChanceLoot` (mode `chance`), as a match on the block id
    and, where the drops depend on the state, on up to three properties."""
    broken = mode != "explosion"
    chance = mode == "chance"
    THIS_ENTITY[0] = not broken
    max_stack = {i["id"]: i["maxStackSize"] for i in dump["items"]}
    rules = {}  # rule text -> block ids
    used_items = set()

    def lean(drops, block_id):
        if drops is None:
            return "none"
        if chance:
            return "some " + drops
        if broken:
            return f"some {len(drops)}"
        for item, _ in drops:
            used_items.add(item)
        items = ", ".join(
            "(%s, %d)" % ("b.id.name" if item == block_id else json.dumps(item), count)
            for item, count in drops)
        return f"some [{items}]"

    for b, tb in zip(dump["blocks"], tnt["blocks"]):
        table = None
        if tb["lootTable"] is not None:
            name = tb["lootTable"].rstrip("]").split(" / ")[1].split(":", 1)[1]
            with open(os.path.join(loot_dir, name + ".json")) as f:
                table = json.load(f)
            # the table draws from its own random sequence, not from the level's generator
            assert "random_sequence" in table, name
        names = [p["name"] for p in b["properties"]]
        per_state = []
        for s in b["states"]:
            props = {p["name"]: p["values"][v] for p, v in zip(b["properties"], s["values"])}
            try:
                if chance:
                    drops = None if table is None else loot_chance(table, b["id"], props, max_stack)
                else:
                    drops = [] if table is None else loot_drops(table, b["id"], props, max_stack)
            except Unknown:
                drops = None
            if broken and SPAWN_AFTER_BREAK & set(b["classes"]):
                drops = None
            per_state.append((props, lean(drops, b["id"])))
        texts = {t for _, t in per_state}
        if len(texts) == 1:
            rule = "    " + texts.pop()
        elif b["id"] in MANY_PROPERTIES:
            rule = "    none"
        else:
            # the smallest set of properties that decides the drops
            keys = None
            for n in (1, 2, 3):
                for cand in combinations(names, n):
                    seen = {}
                    if all(seen.setdefault(tuple(p[k] for k in cand), t) == t
                           for p, t in per_state):
                        keys = cand
                        break
                if keys:
                    break
            assert keys, b["id"]
            seen = {}
            for p, t in per_state:
                seen[tuple(p[k] for k in keys)] = t
            common = Counter(seen.values()).most_common(1)[0][0]
            rule = "    match " + ", ".join(f"prop b {json.dumps(k)}" for k in keys) + " with\n"
            for vs, t in seen.items():
                if t != common:
                    rule += "    | " + ", ".join(json.dumps(v) for v in vs) + " => " + t + "\n"
            rule += "    | " + ", ".join("_" for _ in keys) + " => " + common
        rules.setdefault(rule, []).append(b["id"])

    if chance:
        default = "    none"
        o.append(CHANCE_DOC)
        o.append("def brokenChanceLoot (b : Block) : Option ChanceLoot :=")
    elif broken:
        default = "    some 1"
        o.append("/-- The number of stacks `Block.dropResources` drops for a block that is broken")
        o.append("with drops, without tool and without breaker (a block that lost its support,")
        o.append("for instance), where `brokenChanceLoot` is `none`: the stacks of the block's")
        o.append("loot table. `none` when that is not a function of the block state (chance, a")
        o.append("block entity, neighbouring blocks), or when the block overrides")
        o.append("`spawnAfterBreak`. -/")
        o.append("def brokenDropStacks (b : Block) : Option ℕ :=")
    else:
        default = "    some [(b.id.name, 1)]"
        o.append("/-- The value of the property `key` of a block state; empty if it has none. -/")
        o.append("def prop (b : Block) (key : String) : String :=")
        o.append("  ((b.toProps.find? (·.1 == key)).map (·.2)).getD \"\"")
        o.append("")
        o.append("/-- `BlockState.getDrops` for a block destroyed by an explosion that does not")
        o.append("decay drops: the stacks of the block's loot table, as item and count, for no")
        o.append("tool, no explosion radius and the exploding entity as `this`. `none` when the")
        o.append("drops are not a function of the block state: they depend on chance, on a block")
        o.append("entity or on neighbouring blocks. -/")
        o.append("def explosionDrops (b : Block) : Option (List (String × ℕ)) :=")
    o.append("  match b.id with")
    for rule in sorted(rules, key=lambda r: (len(r), r)):
        if rule != default:
            o.append(match_arms(o, [lean_id(i) for i in rules[rule]]) + " =>")
            o.append(rule)
    o.append("  | _ =>")
    o.append(default)
    o.append("")


