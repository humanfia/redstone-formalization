#!/usr/bin/env python3
"""Generates the block tables of the TNT model.

    source tools/env.sh
    srun -c 2 --mem 4G python3 tools/gen/gen_tnt.py Redstone/Entity/Tnt/Tables.lean

Runs `tools/gen/TntDump.java` on the game jar (a JVM, hence Slurm), which writes
`$MC_REPORTS/tntdump.json`: explosion resistance, speed factor, bounce restitution and loot
table of every block and the voxel grid of every collision shape. Together with the block dump
(`$MC_REPORTS/blockdump.json`, for the shape indices of `Attrs.collision` and the stack sizes of
items) and the block tags and loot tables of the decompiled data pack (`$MC_SRC/data/minecraft`),
this gives `Redstone/Entity/Tnt/Tables.lean`, which must not be edited by hand.

The loot tables are evaluated here, for every block state, as the game evaluates them when a
block is destroyed without a tool: by an explosion that does not decay drops (`explosionDrops`)
and by losing its support (`brokenDropStacks`). The model drops nothing, but the game draws
random numbers for every dropped stack, so the number of stacks is part of the model.

`--no-dump` reuses an existing `tntdump.json`.
"""
import json
import os
import subprocess
import sys
import tempfile
from collections import Counter
from itertools import combinations

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_blocks import ident  # noqa: E402

HEADER = """module

public import Redstone.Block.Basic

/-!
# Block tables for TNT

Generated by `tools/gen/gen_tnt.py` from the Minecraft {version} server. Do not edit.

What primed TNT and explosions need to know about blocks beyond `Block.attrs`: the collision
shapes themselves, and the explosion resistance, speed factor and bounce restitution of every
block, with a few block tags.
-/

set_option linter.all false
set_option maxRecDepth 100000
set_option maxHeartbeats 0

@[expose] public section

namespace Redstone.Entity.Tnt

/-- A collision shape as the game stores it (`VoxelShape`): a grid cut by the coordinates
`xs`, `ys`, `zs` (in blocks, relative to the block's corner) in which some cells are full. -/
structure VoxelGrid where
  /-- The shape is the object `Shapes.block()`, the full cube. -/
  isBlock : Bool
  /-- `getCoords(Axis.X)`: one more coordinate than there are cells along x. -/
  xs : Array Float
  /-- `getCoords(Axis.Y)`. -/
  ys : Array Float
  /-- `getCoords(Axis.Z)`. -/
  zs : Array Float
  /-- The full cells: cell `(x, y, z)` is bit `(x * ny + y) * nz + z`. -/
  full : ℕ
  /-- `toAabbs()`: the boxes of `forAllBoxes`, each as min x, y, z and max x, y, z. -/
  boxes : List (Float × Float × Float × Float × Float × Float)

/-- The empty shape (`Shapes.empty()`). -/
def VoxelGrid.empty : VoxelGrid := ⟨false, #[0], #[0], #[0], 0, []⟩

/-- The `double` with the given bits. -/
def dbl (bits : UInt64) : Float := Float.ofBits bits
"""

FOOTER = "\nend Redstone.Entity.Tnt\n"


def lean_id(block_id):
    return "." + ident(block_id.split(":", 1)[1])


def tag(tags_dir, name, seen=None):
    """The block ids of a block tag, with nested tags resolved."""
    out = []
    with open(os.path.join(tags_dir, name + ".json")) as f:
        for v in json.load(f)["values"]:
            v = v["id"] if isinstance(v, dict) else v
            if v.startswith("#"):
                out += tag(tags_dir, v.split(":", 1)[1])
            else:
                out.append(v)
    return out


def by_value(o, name, doc, typ, of_bits, blocks, key):
    """A function `BlockId → typ` written as a match grouped by value."""
    count = Counter(b[key] for b in blocks)
    default = count.most_common(1)[0][0]
    o.append(f"/-- {doc} -/")
    o.append(f"def {name} : BlockId → {typ}")
    for value in sorted(count):
        if value == default:
            continue
        ids = [lean_id(b["id"]) for b in blocks if b[key] == value]
        line = "  |"
        for i in ids:
            if len(line) + len(i) + 3 > 100:
                o.append(line[:-2])
                line = "  |"
            line += " " + i + " |"
        o.append(line[:-2] + f" => {of_bits} 0x{value}")
    o.append(f"  | _ => {of_bits} 0x{default}")
    o.append("")


def predicate(o, name, doc, ids, known):
    o.append(f"/-- {doc} -/")
    o.append(f"def {name} : BlockId → Bool")
    line = "  |"
    for i in [lean_id(i) for i in ids if i in known]:
        if len(line) + len(i) + 3 > 100:
            o.append(line[:-2])
            line = "  |"
        line += " " + i + " |"
    o.append(line[:-2] + " => true")
    o.append("  | _ => false")
    o.append("")


# Blocks whose drops depend on more than three properties (one item per face): left unknown.
MANY_PROPERTIES = {"minecraft:resin_clump", "minecraft:glow_lichen", "minecraft:sculk_vein"}


# Whether the loot context has the entity `this`: the exploding entity for an explosion, nothing
# for a block that breaks because it lost its support.
THIS_ENTITY = [True]

# Blocks that override `spawnAfterBreak`: broken with drops they may release experience or
# silverfish, which draws from the level's generator.
SPAWN_AFTER_BREAK = {"InfestedBlock", "DropExperienceBlock", "SculkCatalystBlock", "SpawnerBlock",
                     "SculkShriekerBlock", "RedStoneOreBlock", "SculkSensorBlock"}


class Unknown(Exception):
    """The drops depend on something the model does not have (chance, a block entity, ...)."""


def loot_condition(c, block_id, props):
    """A loot condition for a block destroyed by an explosion without drop decay: no tool, no
    explosion radius, and the exploding entity as `this`."""
    if isinstance(c, list):
        return all(loot_condition(x, block_id, props) for x in c)
    if isinstance(c, str):
        if c.startswith("minecraft:tool/"):
            return False  # a predicate on the tool, which is the empty stack
        raise Unknown(c)
    t = c["type"].split(":", 1)[1]
    if t == "survives_explosion":
        return True
    if t == "match_tool":
        return False
    if t == "entity_properties":
        if c["entity"] == "this" and c["predicate"] == {}:
            return THIS_ENTITY[0]  # any entity passes, none fails
        raise Unknown(t)
    if t == "match_block":
        blocks = c["blocks"]
        if isinstance(blocks, str):
            blocks = [blocks]
        if any(b.startswith("#") for b in blocks):
            raise Unknown(t)
        if block_id not in blocks:
            return False
        for k, v in c.get("state", {}).items():
            if isinstance(v, dict):
                value = int(props[k])
                if ("min" in v and value < int(v["min"])) or ("max" in v and value > int(v["max"])):
                    return False
            elif props.get(k) != str(v).lower():
                return False
        return True
    if t == "inverted":
        return not loot_condition(c["term"], block_id, props)
    if t == "all_of":
        return all(loot_condition(x, block_id, props) for x in c["terms"])
    if t == "any_of":
        return any(loot_condition(x, block_id, props) for x in c["terms"])
    raise Unknown(t)  # table_bonus, random_chance, location_check


def loot_modify(stack, modifiers, block_id, props):
    """Applies item functions to a stack `[item, count]`."""
    for m in [modifiers] if isinstance(modifiers, dict) else modifiers:
        if "condition" in m and not loot_condition(m["condition"], block_id, props):
            continue
        t = m["type"].split(":", 1)[1]
        if t == "explosion_decay":
            pass  # no explosion radius without drop decay
        elif t == "set_count":
            if not isinstance(m["count"], (int, float)) or m["count"] != int(m["count"]):
                raise Unknown("count")
            stack[1] = (stack[1] if m.get("add") else 0) + int(m["count"])
        elif t == "apply_bonus":
            # the enchantment level is 0: `ore_drops` and `uniform_bonus_count` change nothing
            if m["formula"].split(":", 1)[1] not in ("ore_drops", "uniform_bonus_count"):
                raise Unknown(m["formula"])
        elif t == "limit_count":
            limit = m["limit"]
            if not isinstance(limit, dict) or not all(isinstance(v, int) for v in limit.values()):
                raise Unknown(t)
            stack[1] = max(stack[1], limit.get("min", stack[1]))
            stack[1] = min(stack[1], limit.get("max", stack[1]))
        elif t == "copy_components" and set(m["include"]) <= {"minecraft:custom_name"}:
            pass  # custom names are not modelled: no block entity has one
        else:
            raise Unknown(t)  # copy_components, copy_state


def loot_expand(entry, block_id, props):
    """The entries a pool entry expands to, or None when its condition fails."""
    if "condition" in entry and not loot_condition(entry["condition"], block_id, props):
        return None
    t = entry["type"].split(":", 1)[1]
    if t == "item":
        if entry.get("weight", 1) != 1:
            raise Unknown("weight")
        return [entry]
    if t == "alternatives":
        for child in entry["children"]:
            expanded = loot_expand(child, block_id, props)
            if expanded is not None:
                return expanded
        return None
    raise Unknown(t)  # dynamic


def loot_drops(table, block_id, props, max_stack):
    """The stacks `BlockState.getDrops` returns for an explosion, as (item, count)."""
    out = []
    for pool in table.get("pools", []):
        if "condition" in pool and not loot_condition(pool["condition"], block_id, props):
            continue
        if not isinstance(pool["rolls"], (int, float)) or pool.get("bonus_rolls", 0) != 0:
            raise Unknown("rolls")
        for _ in range(int(pool["rolls"])):
            valid = []
            for entry in pool["entries"]:
                valid += loot_expand(entry, block_id, props) or []
            if len(valid) > 1:
                raise Unknown("choice")
            for entry in valid:
                stack = [entry["name"], 1]
                loot_modify(stack, entry.get("modifier", []), block_id, props)
                loot_modify(stack, pool.get("modifier", []), block_id, props)
                loot_modify(stack, table.get("modifier", []), block_id, props)
                # `LootTable.createStackSplitter`
                size = max_stack[stack[0]]
                if stack[1] < size:
                    out.append((stack[0], stack[1]))
                else:
                    count = stack[1]
                    while count > 0:
                        out.append((stack[0], min(size, count)))
                        count -= min(size, count)
    return out


def match_arms(o, ids):
    """Writes the alternatives `| .a | .b` of a match arm, wrapped; the last line is returned."""
    line = "  |"
    for i in ids:
        if len(line) + len(i) + 3 > 100:
            o.append(line[:-2])
            line = "  |"
        line += " " + i + " |"
    return line[:-2]


def drops_table(o, dump, tnt, loot_dir, broken):
    """`explosionDrops : Block → Option (List (String × ℕ))` or, with `broken`,
    `brokenDropStacks : Block → Option ℕ`, as a match on the block id and, where the drops
    depend on the state, on up to three properties."""
    THIS_ENTITY[0] = not broken
    max_stack = {i["id"]: i["maxStackSize"] for i in dump["items"]}
    rules = {}  # rule text -> block ids
    used_items = set()

    def lean(drops, block_id):
        if drops is None:
            return "none"
        if broken:
            return f"some {len(drops)}"
        for item, _ in drops:
            used_items.add(item)
        items = ", ".join(
            "(%s, %d)" % ("b.id.name" if item == block_id else json.dumps(item), count)
            for item, count in drops)
        return f"some [{items}]"

    for b, tb in zip(dump["blocks"], tnt["blocks"]):
        table = None
        if tb["lootTable"] is not None:
            name = tb["lootTable"].rstrip("]").split(" / ")[1].split(":", 1)[1]
            with open(os.path.join(loot_dir, name + ".json")) as f:
                table = json.load(f)
            # the table draws from its own random sequence, not from the level's generator
            assert "random_sequence" in table, name
        names = [p["name"] for p in b["properties"]]
        per_state = []
        for s in b["states"]:
            props = {p["name"]: p["values"][v] for p, v in zip(b["properties"], s["values"])}
            try:
                drops = [] if table is None else loot_drops(table, b["id"], props, max_stack)
            except Unknown:
                drops = None
            if broken and SPAWN_AFTER_BREAK & set(b["classes"]):
                drops = None
            per_state.append((props, lean(drops, b["id"])))
        texts = {t for _, t in per_state}
        if len(texts) == 1:
            rule = "    " + texts.pop()
        elif b["id"] in MANY_PROPERTIES:
            rule = "    none"
        else:
            # the smallest set of properties that decides the drops
            keys = None
            for n in (1, 2, 3):
                for cand in combinations(names, n):
                    seen = {}
                    if all(seen.setdefault(tuple(p[k] for k in cand), t) == t
                           for p, t in per_state):
                        keys = cand
                        break
                if keys:
                    break
            assert keys, b["id"]
            seen = {}
            for p, t in per_state:
                seen[tuple(p[k] for k in keys)] = t
            common = Counter(seen.values()).most_common(1)[0][0]
            rule = "    match " + ", ".join(f"prop b {json.dumps(k)}" for k in keys) + " with\n"
            for vs, t in seen.items():
                if t != common:
                    rule += "    | " + ", ".join(json.dumps(v) for v in vs) + " => " + t + "\n"
            rule += "    | " + ", ".join("_" for _ in keys) + " => " + common
        rules.setdefault(rule, []).append(b["id"])

    if broken:
        default = "    some 1"
        o.append("/-- The number of stacks `Block.dropResources` drops for a block that is broken")
        o.append("with drops, without tool and without breaker (a block that lost its support,")
        o.append("for instance): the stacks of the block's loot table. `none` when that is not a")
        o.append("function of the block state (chance, a block entity, neighbouring blocks), or")
        o.append("when the block overrides `spawnAfterBreak`. -/")
        o.append("def brokenDropStacks (b : Block) : Option ℕ :=")
    else:
        default = "    some [(b.id.name, 1)]"
        o.append("/-- The value of the property `key` of a block state; empty if it has none. -/")
        o.append("def prop (b : Block) (key : String) : String :=")
        o.append("  ((b.toProps.find? (·.1 == key)).map (·.2)).getD \"\"")
        o.append("")
        o.append("/-- `BlockState.getDrops` for a block destroyed by an explosion that does not")
        o.append("decay drops: the stacks of the block's loot table, as item and count, for no")
        o.append("tool, no explosion radius and the exploding entity as `this`. `none` when the")
        o.append("drops are not a function of the block state: they depend on chance, on a block")
        o.append("entity or on neighbouring blocks. -/")
        o.append("def explosionDrops (b : Block) : Option (List (String × ℕ)) :=")
    o.append("  match b.id with")
    for rule in sorted(rules, key=lambda r: (len(r), r)):
        if rule != default:
            o.append(match_arms(o, [lean_id(i) for i in rules[rule]]) + " =>")
            o.append(rule)
    o.append("  | _ =>")
    o.append(default)
    o.append("")


def main():
    args =[a for a in sys.argv[1:] if not a.startswith("--")]
    out_path = args[0]
    reports = os.environ["MC_REPORTS"]
    here = os.path.dirname(os.path.abspath(__file__))
    dump_path = os.path.join(reports, "tntdump.json")
    if "--no-dump" not in sys.argv:
        with open(os.path.join(os.environ["MC_HOME"], "harness-build", "classpath")) as f:
            classpath = f.read().strip()
        # the game writes a `logs` directory where it starts
        with tempfile.TemporaryDirectory(dir=reports) as run_dir:
            subprocess.run(
                ["java", "-cp", classpath, os.path.join(here, "TntDump.java"), dump_path],
                check=True, cwd=run_dir, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    with open(dump_path) as f:
        tnt = json.load(f)
    with open(os.path.join(reports, "blockdump.json")) as f:
        dump = json.load(f)
    tags_dir = os.path.join(os.environ["MC_SRC"], "data", "minecraft", "tags", "block")

    # The grid of each collision shape index of the block dump.
    grid_of = {}
    for b, tb in zip(dump["blocks"], tnt["blocks"]):
        assert b["id"] == tb["id"] and len(b["states"]) == len(tb["states"]), b["id"]
        for s, g in zip(b["states"], tb["states"]):
            index = s["attrs"]["collision"]
            assert grid_of.setdefault(index, g) == g, (b["id"], index)
            assert dump["shapes"][index] == tnt["grids"][g]["boxes"], b["id"]

    o = [HEADER.format(version=tnt["version"])]
    o.append("/-- The collision shape with the given index (`Attrs.collision`), as the block")
    o.append("returns it for an empty collision context at the origin. -/")
    o.append("def collisionGrid : ℕ → VoxelGrid")
    for index in sorted(grid_of):
        g = tnt["grids"][grid_of[index]]
        if not g["boxes"]:
            continue
        nx, ny, nz = len(g["xs"]) - 1, len(g["ys"]) - 1, len(g["zs"]) - 1
        assert len(g["full"]) == nx * ny * nz
        full = sum(1 << i for i, c in enumerate(g["full"]) if c == "1")
        coords = lambda cs: "#[" + ", ".join(f"dbl 0x{c}" for c in cs) + "]"
        boxes = ", ".join("(" + ", ".join(f"dbl 0x{c}" for c in box) + ")" for box in g["boxes"])
        o.append(f"  | {index} => ⟨{'true' if g['block'] else 'false'}, {coords(g['xs'])}, "
                 f"{coords(g['ys'])}, {coords(g['zs'])}, 0x{full:x}, [{boxes}]⟩")
    o.append("  | _ => .empty")
    o.append("")

    blocks = tnt["blocks"]
    known = {b["id"] for b in blocks}
    by_value(o, "explosionResistance", "`Block.getExplosionResistance()`.", "Float32",
             "Float32.ofBits", blocks, "explosionResistance")
    by_value(o, "speedFactor", "`Block.getSpeedFactor()`.", "Float32", "Float32.ofBits", blocks,
             "speedFactor")
    by_value(o, "bounceRestitution", "`Block.getBounceRestitution()`.", "Float32",
             "Float32.ofBits", blocks, "bounceRestitution")
    predicate(o, "hasDynamicShape", "`Block.hasDynamicShape()`: the shapes of the block may "
              "depend on more than its state.", [b["id"] for b in blocks if b["dynamicShape"]],
              known)
    predicate(o, "hasDynamicCollision", "`hasDynamicShape` for a block that has collision.",
              [b["id"] for b in blocks if b["dynamicShape"] and b["hasCollision"]], known)
    predicate(o, "suppressesBounce", "The block tag `suppresses_bounce`.",
              tag(tags_dir, "suppresses_bounce"), known)
    predicate(o, "fallDamageResetting", "The block tag `fall_damage_resetting`.",
              tag(tags_dir, "fall_damage_resetting"), known)
    predicate(o, "isFence", "The block tag `fences`.", tag(tags_dir, "fences"), known)
    predicate(o, "isWall", "The block tag `walls`.", tag(tags_dir, "walls"), known)
    predicate(o, "isFenceGate", "The block is a `FenceGateBlock`.",
              [b["id"] for b in dump["blocks"] if "FenceGateBlock" in b["classes"]], known)
    loot_dir = os.path.join(os.environ["MC_SRC"], "data", "minecraft", "loot_table")
    drops_table(o, dump, tnt, loot_dir, False)
    drops_table(o, dump, tnt, loot_dir, True)
    o.append(FOOTER)
    with open(out_path, "w") as f:
        f.write("\n".join(o))


if __name__ == "__main__":
    main()
