    dump_path = os.path.join(reports, "tntdump.json")
    if "--no-dump" not in sys.argv:
        with open(os.path.join(os.environ["MC_HOME"], "harness-build", "classpath")) as f:
            classpath = f.read().strip()
        # the game writes a `logs` directory where it starts
        with tempfile.TemporaryDirectory(dir=reports) as run_dir:
            subprocess.run(
                ["java", "-cp", classpath, os.path.join(here, "TntDump.java"), dump_path],
                check=True, cwd=run_dir, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    with open(dump_path) as f:
        tnt = json.load(f)
    with open(os.path.join(reports, "blockdump.json")) as f:
        dump = json.load(f)
    tags_dir = os.path.join(os.environ["MC_SRC"], "data", "minecraft", "tags", "block")

    # The grid of each collision shape index of the block dump.
    grid_of = {}
    for b, tb in zip(dump["blocks"], tnt["blocks"]):
        assert b["id"] == tb["id"] and len(b["states"]) == len(tb["states"]), b["id"]
        for s, g in zip(b["states"], tb["states"]):
            index = s["attrs"]["collision"]
            assert grid_of.setdefault(index, g) == g, (b["id"], index)
            assert dump["shapes"][index] == tnt["grids"][g]["boxes"], b["id"]

    o = [HEADER.format(version=tnt["version"])]
    o.append("/-- The collision shape with the given index (`Attrs.collision`), as the block")
    o.append("returns it for an empty collision context at the origin. -/")
    o.append("def collisionGrid : ℕ → VoxelGrid")
    for index in sorted(grid_of):
        g = tnt["grids"][grid_of[index]]
        if not g["boxes"]:
            continue
        nx, ny, nz = len(g["xs"]) - 1, len(g["ys"]) - 1, len(g["zs"]) - 1
        assert len(g["full"]) == nx * ny * nz
        full = sum(1 << i for i, c in enumerate(g["full"]) if c == "1")
        coords = lambda cs: "#[" + ", ".join(f"dbl 0x{c}" for c in cs) + "]"
        boxes = ", ".join("(" + ", ".join(f"dbl 0x{c}" for c in box) + ")" for box in g["boxes"])
        o.append(f"  | {index} => ⟨{'true' if g['block'] else 'false'}, {coords(g['xs'])}, "
                 f"{coords(g['ys'])}, {coords(g['zs'])}, 0x{full:x}, [{boxes}]⟩")
    o.append("  | _ => .empty")
    o.append("")

    blocks = tnt["blocks"]
    known = {b["id"] for b in blocks}
    by_value(o, "explosionResistance", "`Block.getExplosionResistance()`.", "Float32",
             "Float32.ofBits", blocks, "explosionResistance")
    by_value(o, "speedFactor", "`Block.getSpeedFactor()`.", "Float32", "Float32.ofBits", blocks,
             "speedFactor")
    by_value(o, "bounceRestitution", "`Block.getBounceRestitution()`.", "Float32",
             "Float32.ofBits", blocks, "bounceRestitution")
    predicate(o, "hasDynamicShape", "`Block.hasDynamicShape()`: the shapes of the block may "
              "depend on more than its state.", [b["id"] for b in blocks if b["dynamicShape"]],
              known)
    predicate(o, "hasDynamicCollision", "`hasDynamicShape` for a block that has collision.",
              [b["id"] for b in blocks if b["dynamicShape"] and b["hasCollision"]], known)
    predicate(o, "suppressesBounce", "The block tag `suppresses_bounce`.",
              tag(tags_dir, "suppresses_bounce"), known)
    predicate(o, "fallDamageResetting", "The block tag `fall_damage_resetting`.",
              tag(tags_dir, "fall_damage_resetting"), known)
    predicate(o, "isFence", "The block tag `fences`.", tag(tags_dir, "fences"), known)
    predicate(o, "isWall", "The block tag `walls`.", tag(tags_dir, "walls"), known)
    predicate(o, "isFenceGate", "The block is a `FenceGateBlock`.",
              [b["id"] for b in dump["blocks"] if "FenceGateBlock" in b["classes"]], known)
    loot_dir = os.path.join(os.environ["MC_SRC"], "data", "minecraft", "loot_table")
    drops_table(o, dump, tnt, loot_dir, "explosion")
    drops_table(o, dump, tnt, loot_dir, "broken")
    drops_table(o, dump, tnt, loot_dir, "chance")
    o.append(FOOTER)
    with open(out_path, "w") as f:
        f.write("\n".join(o))


